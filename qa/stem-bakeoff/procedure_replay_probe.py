def write_json(path, value):
    with Path(path).open("xb") as stream:
        stream.write(canonical(value) + b"\n")


def write_lines(path, rows):
    with Path(path).open("xb") as raw:
        with gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as stream:
            for row in rows:
                stream.write(canonical(row) + b"\n")


def source_closure():
    pending = ["procedure_replay_probe.py", "procedure_replay_learning.py",
               "procedure_replay_evaluation.py", "procedure_replay_owner.py"]
    files = {}
    while pending:
        name = pending.pop()
        if name in files:
            continue
        path = ROOT / name
        raw = path.read_bytes()
        files[name] = sha(raw)
        for node in ast.walk(ast.parse(raw)):
            names = ([node.module] if isinstance(node, ast.ImportFrom) else
                     [alias.name for alias in node.names] if isinstance(node, ast.Import) else [])
            for module in names:
                candidate = (module or "").split(".")[0] + ".py"
                if (ROOT / candidate).is_file():
                    pending.append(candidate)
    files["real_encoder_candidates.json"] = sha((ROOT / "real_encoder_candidates.json").read_bytes())
    return dict(sorted(files.items()))


