def require_plan(target, expected_sha256=None):
    target = Path(target)
    raw = (target / "plan.json").read_bytes()
    if expected_sha256 is not None and sha(raw) != expected_sha256:
        raise ValueError("plan differs from the externally retained preregistration digest")
    plan = json.loads(raw)
    if (plan["source_code_sha256"] != source_closure()
            or plan["case_specification_sha256"] != sha(canonical([
                {"query": asdict(case.query), "goal": case.goal} for case in make_cases()]))):
        raise ValueError("frozen source or case plan changed; do not overwrite old evidence")
    for case in make_cases():
        raw = (target / "inputs" / (case.query.input_family + ".json")).read_bytes()
        if raw != case.input_bytes:
            raise ValueError("frozen input file changed")
    return plan


def attempt(case, choice):
    """Observer receives goal; prediction code receives Query, never Case."""
    with tempfile.TemporaryDirectory(prefix="hepta-procedure-attempt-") as directory:
        source = Path(directory) / "data.json"
        output = Path(directory) / "output.json"
        source.write_bytes(case.input_bytes)
        execution = execute(choice, source, output)
        checked = observe(case.goal, source, output, case.query.input_sha256)
    return {"query_id": case.query.query_id, "input_family": case.query.input_family,
            "template_family": case.query.template_family, "split": case.query.split,
            "choice": choice, "execution": execution, "observation": checked}


def observe_replay(target):
    target = Path(target)
    require_plan(target)
    attempts, labels = [], {}
    for case in make_cases():
        rows = [attempt(case, choice) for choice in range(4)]
        attempts.extend(rows)
        success = [row["choice"] for row in rows if row["observation"]["success"]]
        labels[case.query.query_id] = success
    write_lines(target / "replay_attempts.jsonl.gz", attempts)
    summary = {"attempts": len(attempts), "successful_attempts": sum(
               row["observation"]["success"] for row in attempts),
               "execution_calls": sum(row["execution"]["execution_calls"] for row in attempts),
               "execution_ns": sum(row["execution"]["elapsed_ns"] for row in attempts),
               "failed_attempts": sum(not row["observation"]["success"] for row in attempts),
               "execution_errors": sum(row["execution"]["execution_error"] is not None for row in attempts),
               "ambiguous_or_unsolved_queries": {key: value for key, value in labels.items() if len(value) != 1},
               "attempts_by_split": {split: sum(row["split"] == split for row in attempts) for split in SPLITS},
               "replay_sha256": sha((target / "replay_attempts.jsonl.gz").read_bytes()),
               "observer_code_sha256": sha((ROOT / "procedure_replay_observer.py").read_bytes()),
               "independent_organization_or_signature": False}
    write_json(target / "replay_summary.json", summary)
    if summary["ambiguous_or_unsolved_queries"]:
        raise ValueError("predeclared task is ambiguous or unsolved; retain evidence and stop")
    return summary


def replay_labels(target):
    target = Path(target)
    summary = json.loads((target / "replay_summary.json").read_bytes())
    if sha((target / "replay_attempts.jsonl.gz").read_bytes()) != summary["replay_sha256"]:
        raise ValueError("replay evidence changed")
    labels, counts = {}, {}
    with gzip.open(target / "replay_attempts.jsonl.gz", "rt") as stream:
        for line in stream:
            row = json.loads(line)
            counts[row["query_id"]] = counts.get(row["query_id"], 0) + 1
            if row["observation"]["success"]:
                if row["query_id"] in labels:
                    raise ValueError("ambiguous observed label")
                labels[row["query_id"]] = row["choice"]
    if set(labels) != {case.query.query_id for case in make_cases()} or set(counts.values()) != {4}:
        raise ValueError("incomplete observed replay")
    return labels


class ReplayBM25:
    """Training-success retrieval, no access to heldout goal or output bytes."""
    def __init__(self, training_queries, observed_labels):
        self.rows = tuple(training_queries)
        if any(query.split != "train" for query in self.rows):
            raise ValueError("retrieval index accepts only training replay")
        self.labels = tuple(observed_labels[query.query_id] for query in self.rows)
        self.db = sqlite3.connect(":memory:")
        self.db.execute("CREATE VIRTUAL TABLE replay USING fts5(text, tokenize='porter unicode61')")
        self.db.executemany("INSERT INTO replay(rowid,text) VALUES (?,?)",
                            [(index + 1, query.text) for index, query in enumerate(self.rows)])
        self.db.commit()
        self.retained_bytes = len(self.db.serialize())

    def scores(self, query):
        import re
        tokens = sorted(set(re.findall(r"[a-z]+", query.text.casefold())))
        expression = " OR ".join('"' + token + '"' for token in tokens)
        start = time.perf_counter_ns()
        hits = self.db.execute("SELECT rowid,bm25(replay) FROM replay WHERE replay MATCH ?",
                               (expression,)).fetchall() if tokens else []
        scores = [0.0] * 4
        for row, score in hits:
            label = self.labels[row - 1]
            scores[label] = max(scores[label], -score)
        return scores, {"selector_ns": time.perf_counter_ns() - start, "matched_replay_rows": len(hits)}


def observe_phase(target, expected_plan_sha256=None):
    from procedure_replay_evaluation import evaluate_policy
    require_plan(target, expected_plan_sha256)
    replay = observe_replay(target)
    labels = replay_labels(target)
    cases = make_cases()
    index = ReplayBM25([case.query for case in cases if case.query.split == "train"], labels)
    rows, overhead = {}, {}
    for case in cases:
        if case.query.split in ("development", "heldout"):
            scores, cost = index.scores(case.query)
            rows[case.query.query_id] = max(range(4), key=lambda label: (scores[label], -label))
            overhead[case.query.query_id] = cost
    result = evaluate_policy(cases, rows, arm="bm25_replay", policy="forced", costs=overhead)
    write_lines(Path(target) / "bm25_evaluation.jsonl.gz", result["rows"])
    write_json(Path(target) / "observe_report.json", {
        "replay": replay, "bm25": result["summary"], "bm25_index_bytes": index.retained_bytes,
        "python": platform.python_version(), "sqlite": sqlite3.sqlite_version,
        "encoder_run": False, "head_training_run": False, "status": "awaiting_pinned_encoder"})
    index.db.close()
    return result["summary"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("phase", choices=("freeze", "observe", "learn"))
    parser.add_argument("--output", required=True)
    parser.add_argument("--snapshot")
    parser.add_argument("--expected-plan-sha256")
    parser.add_argument("--operator-accepted-terms", action="store_true")
    args = parser.parse_args()
    if args.phase != "freeze" and not args.expected_plan_sha256:
        parser.error("observe/learn require the externally retained --expected-plan-sha256")
    if args.phase == "freeze":
        result = freeze(args.output)
    elif args.phase == "observe":
        result = observe_phase(args.output, args.expected_plan_sha256)
    else:
        from procedure_replay_learning import learn
        result = learn(args.output, args.snapshot, args.operator_accepted_terms, args.expected_plan_sha256)
    print(json.dumps(result, sort_keys=True, indent=2))


if __name__ == "__main__":
    main()
