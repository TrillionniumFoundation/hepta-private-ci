def main():
    root = Path(__file__).resolve().parent
    rows = []
    for op, prompts in SUPPORTED.items():
        assert len(prompts) == 20
        for i, text in enumerate(prompts, 1):
            rows.append({"id": f"independent-v6-{op}-{i:02d}", "utterance": text,
                         "expected_operation": op, "family": op})
    for family, prompts in OOD.items():
        assert len(prompts) == 6
        for i, text in enumerate(prompts, 1):
            rows.append({"id": f"independent-v6-ood-{family}-{i:02d}", "utterance": text,
                         "expected_operation": None, "family": family})
    assert len(rows) == 180
    assert len({x["utterance"] for x in rows}) == 180
    body = "".join(json.dumps(x, ensure_ascii=False, sort_keys=True) + "\n" for x in rows)
    target = root / "independent_held_requests.jsonl"
    target.write_text(body, encoding="utf-8")
    manifest = {
        "schema": "hepta.cell.semantic.independent-held.v1",
        "author": "root assistant, separate from training agent",
        "not_human_authored": True,
        "language": "en",
        "supported": 120,
        "out_of_distribution": 60,
        "request_count": len(rows),
        "held_sha256": hashlib.sha256(body.encode()).hexdigest(),
        "date_and_series": "Provided explicitly by evaluator from the frozen numeric task; templates do not supply or change them.",
        "release_rule": "Release only after candidate source, training data, selection rule and selected candidate hashes are frozen.",
        "limitations": ["Synthetic assistant-authored holdout", "English only", "Finite six-operation task", "No general intelligence claim"],
    }
    (root / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps(manifest, ensure_ascii=False))

if __name__ == "__main__":
    main()

