"""One reviewed storage-only qualification, not six model or candidate runs.

Run from the containing workspace root with an ALREADY EXISTING shared lock.
No automatic retry, no private replacement lock, no remote work.
"""
import fcntl
import hashlib
import json
import os
from pathlib import Path
import resource
import signal
import stat
import subprocess
import sys
import time

ROOT=Path(__file__).absolute().parent
OUT=ROOT/'RUN_ONCE'
H=lambda b:hashlib.sha256(b).hexdigest()

def canonical(value):return (json.dumps(value,indent=2,sort_keys=True,allow_nan=False)+'\n').encode('ascii')

def regular(path):
    path=Path(os.path.abspath(path))
    for p in [*reversed(path.parents),path]:
        if p.is_symlink():raise ValueError('symlink path refused')
    if not stat.S_ISREG(path.stat().st_mode):raise ValueError('regular file required')
    return path


def main():
    # Full prefix starts before lock/freeze checks, not at child spawn.
    start=time.monotonic();cpu0=time.process_time();usage0=resource.getrusage(resource.RUSAGE_SELF)
    if len(sys.argv)!=2:raise ValueError('one existing shared benchmark lock path required')
    lock_path=regular(sys.argv[1])
    lock=open(lock_path,'rb')
    fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
    for r,n in [(resource.RLIMIT_CPU,4),(resource.RLIMIT_AS,256*2**20),(resource.RLIMIT_FSIZE,8*2**20)]:resource.setrlimit(r,(n,n))
    # No capsule modules imported: parse small control documents only.
    freeze_path=regular(ROOT/'FREEZE.json');freeze=json.loads(freeze_path.read_bytes())
    capacity=json.loads(regular(ROOT/'CAPACITY.json').read_bytes())
    for rel,pin in freeze.items():
        p=regular(ROOT/rel)
        if p.stat().st_size>511999:raise ValueError('source/package blob size')
        b=p.read_bytes()
        if len(b)>511999 or H(b)!=pin:raise ValueError('source/package freeze drift: '+rel)
    admission_path=regular(ROOT/'SOURCE_REVIEW.json')
    admission=json.loads(admission_path.read_bytes())
    if admission.get('source_freeze_sha256')!=H(freeze_path.read_bytes()) or admission.get('qualification_admitted') is not True:
        raise ValueError('independent source review/admission binding required')
    # The independent reviewer may add findings, but the run is scoped to this
    # exact reviewed freeze. No review is generated by this runner.
    OUT.mkdir(exist_ok=False)
    record={'status':'STARTED','scope':'stdlib storage/materialization only',
            'source_freeze_sha256':H(freeze_path.read_bytes()),'source_review_sha256':H(admission_path.read_bytes()),
            'manifest_sha256':H((ROOT/'capsule-manifest.json').read_bytes()),
            'lock_existing':True,'lock_path':str(lock_path),'lock_created':False,
            'retry':False,'automatic_next_run_authorized':False,
            'limits':{'child_CPU_soft_hard_seconds':[3,3],'outer_CPU_soft_hard_seconds':[4,4],
                      'child_wall_seconds':15,'AS_bytes':256*2**20,'FSIZE_per_file_bytes':8*2**20,
                      'retained_output_bytes':capacity['retained_output_max_bytes'],
                      'retained_output_files':capacity['retained_output_max_files']}}
    p=None;reaped=False;usage=None;child_started=None;timed_out=False
    def setup():
        resource.setrlimit(resource.RLIMIT_CPU,(3,3))
        signal.signal(signal.SIGALRM,signal.SIG_DFL);signal.alarm(15)
    try:
        with (OUT/'tests.log').open('xb') as log:
            child_started=time.monotonic()
            p=subprocess.Popen([sys.executable,'-I','-B',str(ROOT/'test_materialize.py'),str(OUT)],stdout=log,stderr=subprocess.STDOUT,preexec_fn=setup)
            while True:
                pid,status,usage=os.wait4(p.pid,os.WNOHANG)
                if pid:
                    reaped=True;p.returncode=os.waitstatus_to_exitcode(status);break
                if time.monotonic()-child_started>=15:
                    timed_out=True;p.kill();pid,status,usage=os.wait4(p.pid,0)
                    reaped=True;p.returncode=os.waitstatus_to_exitcode(status);break
                time.sleep(.01)
        record.update(status='CANDIDATE_CHILD_PASSED' if p.returncode==0 and not timed_out else 'FAILED',
                      child_PID=p.pid,child_exit_code=p.returncode,timed_out=timed_out,
                      complete_wait4=reaped,wait4_rusage=list(usage),
                      child_user_CPU_seconds=usage.ru_utime,child_system_CPU_seconds=usage.ru_stime,
                      child_maxRSS_KiB=usage.ru_maxrss)
    except BaseException as error:
        record.update(status='FAILED_LAUNCH_OR_MONITOR',error=repr(error))
        if p is not None and not reaped:
            try:
                p.kill();pid,status,usage=os.wait4(p.pid,0);reaped=True;p.returncode=os.waitstatus_to_exitcode(status)
                record.update(cleanup_exit=p.returncode,cleanup_wait4_rusage=list(usage),complete_wait4=True)
            except (OSError,ChildProcessError) as cleanup:record['cleanup_error']=repr(cleanup)
    # Tail, incomplete/failed spawn cost and hard-kill receipt loss are not zero.
    record.update(wall_prefix_seconds=time.monotonic()-start,
                  outer_CPU_prefix_seconds=time.process_time()-cpu0,
                  outer_rusage_before=list(usage0),outer_rusage_prefix=list(resource.getrusage(resource.RUSAGE_SELF)),
                  outer_tail='unknown_not_zero',
                  failure_boundary='Handled errors attempt own-child kill/reap. Outer hard kill, kernel stalls or disk errors can prevent terminal receipt. Failed Popen may incur internally reaped launch work without an individual child receipt. No model or descendant subprocess is launched by tests.',
                  total_bound_scope='Explicit before-run inventory-derived fixture limits plus terminal recursive inventory; not a filesystem quota, hostile mutation protection, or RLIMIT_FSIZE aggregate enforcement.')
    inventory={}
    for f in sorted(OUT.rglob('*')):
        if f.is_symlink():raise ValueError('unexpected output symlink')
        if f.is_file():
            b=f.read_bytes();inventory[str(f.relative_to(OUT))]={'bytes':len(b),'sha256':H(b)}
    record['known_CPU_lower_bound_seconds']=record['outer_CPU_prefix_seconds']+((usage.ru_utime+usage.ru_stime) if usage else 0)
    record['inventory']=inventory
    base=sum(x['bytes'] for x in inventory.values())
    report=json.loads((OUT/'TEST_REPORT.json').read_bytes()) if (OUT/'TEST_REPORT.json').is_file() else {}
    ok=(record['status']=='CANDIDATE_CHILD_PASSED' and report.get('negative_count')==capacity['negative_cases']
        and report.get('positive_count')==capacity['positive_cases']
        and usage is not None and usage.ru_utime+usage.ru_stime<=3 and usage.ru_maxrss*1024<=256*2**20
        and all(x['bytes']<=8*2**20 for x in inventory.values())
        and inventory.get('tests.log',{}).get('bytes',capacity['tests_log_max_bytes']+1)<=capacity['tests_log_max_bytes']
        and inventory.get('TEST_REPORT.json',{}).get('bytes',capacity['test_report_max_bytes']+1)<=capacity['test_report_max_bytes'])
    record['terminal_budget_pass']=False;record['final_retained_bytes']=0
    for _ in range(20):
        raw=canonical(record);total=base+len(raw)
        passed=ok and total<=capacity['retained_output_max_bytes'] and len(inventory)+1<=capacity['retained_output_max_files'] and len(raw)<=capacity['outer_receipt_max_bytes']
        status='PASS_PACKAGING_ONLY_NOT_SCIENTIFIC_OR_COMBINED_RUNTIME' if passed else 'FAILED'
        if record['final_retained_bytes']==total and record['terminal_budget_pass']==passed and record['status']==status:break
        record.update(final_retained_bytes=total,terminal_budget_pass=passed,status=status)
    else:raise ValueError('receipt size fixed point failed')
    with (OUT/'OUTER_WAIT4_RECEIPT.json').open('xb') as stream:stream.write(raw)
    lock.close()
    print(json.dumps({'status':record['status'],'terminal_budget_pass':passed,'final_retained_bytes':total,'child_CPU_seconds':(usage.ru_utime+usage.ru_stime) if usage else None},sort_keys=True))
    return 0 if passed else 1


if __name__=='__main__':raise SystemExit(main())
