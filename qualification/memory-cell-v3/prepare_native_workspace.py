#!/usr/bin/env python3
"""Extract the three real native crates without changing production manifests.

Source directories are linked to the checkout, so tests/fixes compile and edit
the real files. Manifests, the original nextest policy and lint policy retain
their source identity. The reduced lock must contain only exact name/version/
source/checksum tuples from the repository lock. This is isolated qualification,
not evidence that the full product workspace resolves or has passed admission.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tomllib


CRATES = ("hepta-types", "hepta-infer-core", "hepta-neuron")
DIRECT = ("serde", "serde_json", "sha2", "pretty_assertions")


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def atom(value):
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(atom(item) for item in value) + "]"
    if isinstance(value, dict):
        return (
            "{"
            + ", ".join(f"{key} = {atom(item)}" for key, item in value.items())
            + "}"
        )
    raise TypeError(f"unsupported manifest value {type(value)}")


def identity(package):
    return package["name"], package["version"], package.get("source", "")


def closure(packages):
    selected = {}
    pending = [f"codex-{crate}" for crate in CRATES]
    while pending:
        dependency = pending.pop()
        pieces = dependency.split(" ", 2)
        matches = [
            package
            for package in packages
            if package["name"] == pieces[0]
            and (len(pieces) < 2 or package["version"] == pieces[1])
        ]
        if len(matches) != 1:
            raise ValueError(f"ambiguous source lock dependency: {dependency}")
        package = matches[0]
        key = identity(package)
        if key not in selected:
            selected[key] = package
            pending.extend(package.get("dependencies", []))
    return selected


def isolated_nextest(source, destination):
    """Only remove package-scoped overrides whose packages are absent here."""
    original = source.read_text()
    included = {f"codex-{crate}" for crate in CRATES}
    blocks = re.split(r"(?m)(?=^\[\[profile\.[^.]+\.overrides\]\])", original)
    active, removed = [], []
    for block in blocks:
        # A following non-override table belongs to the retained policy, not
        # to the package-specific override being considered for extraction.
        sections = re.split(r"(?m)(?=^\[(?!\[))", block, maxsplit=1)
        override = sections[0]
        packages = re.findall(r"package\(([^)]+)\)", override)
        if (
            override.startswith("[[profile.")
            and packages
            and all(name not in included for name in packages)
        ):
            removed.append(
                {
                    "absent_packages": packages,
                    "override_sha256": hashlib.sha256(override.encode()).hexdigest(),
                }
            )
            active.extend(sections[1:])
        else:
            active.append(block)
    (destination.parent / "nextest.source.toml").write_text(original)
    destination.write_text(
        "# Isolated workspace: only overrides for absent packages removed.\n"
        + "".join(active)
    )
    return removed


def prepare(root, destination, offline):
    root, destination = root.resolve(), destination.resolve()
    source = root / "codex-rs"
    manifest_path, lock_path = source / "Cargo.toml", source / "Cargo.lock"
    original = tomllib.loads(manifest_path.read_text())
    original_lock_text = lock_path.read_text()
    original_lock = tomllib.loads(original_lock_text)
    included = closure(original_lock["package"])
    marker = destination / "memory-cell-isolated-workspace.json"
    if destination.exists() and not marker.is_file():
        raise ValueError("destination exists without this extractor's ownership marker")
    destination.mkdir(parents=True, exist_ok=True)
    marker.write_text(
        json.dumps(
            {"schema": "hepta.memory.isolated-workspace.v1", "checkout": str(root)},
            indent=2,
        )
        + "\n"
    )
    lines = [
        "# Generated by qualification/memory-cell-v3/prepare_native_workspace.py",
        "[workspace]",
        f"members = {atom(list(CRATES))}",
        f"resolver = {atom(original['workspace']['resolver'])}",
        "",
        "[workspace.package]",
    ]
    lines.extend(
        f"{key} = {atom(value)}"
        for key, value in original["workspace"]["package"].items()
    )
    lines.extend(["", "[workspace.dependencies]"])
    for name in DIRECT:
        locked = [package for package in included.values() if package["name"] == name]
        if len(locked) != 1:
            raise ValueError(f"ambiguous isolated direct dependency {name}")
        value = original["workspace"]["dependencies"][name]
        value = {"version": value} if isinstance(value, str) else dict(value)
        value["version"] = "=" + locked[0]["version"]
        lines.append(f"{name} = {atom(value)}")
    lines.extend(["", "[workspace.lints]"])
    lines.extend(
        f"{key} = {atom(value)}"
        for key, value in original["workspace"]["lints"].items()
    )
    (destination / "Cargo.toml").write_text("\n".join(lines) + "\n")
    inventory = {}
    for crate in CRATES:
        crate_source, crate_destination = source / crate, destination / crate
        crate_destination.mkdir(exist_ok=True)
        for child in sorted(crate_source.iterdir()):
            target = crate_destination / child.name
            if child.is_dir():
                if target.is_symlink():
                    if target.resolve() != child.resolve():
                        raise ValueError(f"unexpected source link {target}")
                elif target.exists():
                    raise ValueError(
                        f"source directory must remain a checkout link: {target}"
                    )
                else:
                    target.symlink_to(child, target_is_directory=True)
            elif child.is_file():
                shutil.copyfile(child, target)
        for file in sorted(crate_source.rglob("*")):
            if file.is_file():
                inventory[str(file.relative_to(root))] = digest(file)
    nextest_removed = []
    for relative in (".config/nextest.toml", "clippy.toml", "rustfmt.toml"):
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source / relative, target)
        if relative == ".config/nextest.toml":
            nextest_removed = isolated_nextest(source / relative, target)
        inventory[f"codex-rs/{relative}"] = digest(source / relative)
    blocks = re.split(r"(?m)^\[\[package\]\]\n", original_lock_text)
    kept = [blocks[0]]
    for block in blocks[1:]:
        entry = tomllib.loads("[[package]]\n" + block)["package"][0]
        if identity(entry) in included:
            kept.append("[[package]]\n" + block)
    (destination / "Cargo.lock").write_text("".join(kept))
    command = [
        "cargo",
        "metadata",
        "--format-version",
        "1",
        "--manifest-path",
        str(destination / "Cargo.toml"),
    ]
    if offline:
        command.append("--offline")
    # Cargo may remove feature-unified edges belonging to excluded crates. It
    # may not select a new version or registry checksum: verify that below.
    subprocess.run(command, check=True, stdout=subprocess.PIPE)
    reduced = tomllib.loads((destination / "Cargo.lock").read_text())
    original_by_identity = {
        identity(package): package for package in original_lock["package"]
    }
    dependencies = []
    for package in reduced["package"]:
        reference = original_by_identity.get(identity(package))
        if reference is None or package.get("checksum") != reference.get("checksum"):
            raise ValueError(
                f"isolated resolution drifted from original lock: {identity(package)}"
            )
        dependencies.append(
            {
                key: package[key]
                for key in ("name", "version", "source", "checksum")
                if key in package
            }
        )
    receipt = {
        "schema": "hepta.memory.native-source-identity.v1",
        "qualification_scope": "three real crates in an extracted dependency workspace; not full workspace or product admission",
        "checkout": str(root),
        "checkout_head": subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=root, text=True
        ).strip(),
        "source_directories": "linked directly to checkout; manifests copied byte-for-byte",
        "source_files": inventory,
        "source_workspace_manifest_sha256": digest(manifest_path),
        "source_lock_sha256": digest(lock_path),
        "extracted_manifest_sha256": digest(destination / "Cargo.toml"),
        "extracted_lock_sha256": digest(destination / "Cargo.lock"),
        "dependencies": dependencies,
        "nextest_absent_package_overrides": nextest_removed,
        "active_nextest_sha256": digest(destination / ".config/nextest.toml"),
    }
    (destination / "source-identity.json").write_text(
        json.dumps(receipt, indent=2, sort_keys=True) + "\n"
    )
    print(
        json.dumps(
            {
                "workspace": str(destination),
                "source_files": len(inventory),
                "exact_lock_packages": len(dependencies),
                "source_identity_sha256": digest(destination / "source-identity.json"),
            }
        )
    )
    return destination, receipt


def build_example(destination, identity, offline):
    command = [
        "cargo",
        "build",
        "--locked",
        "--manifest-path",
        str(destination / "Cargo.toml"),
        "-p",
        "codex-hepta-neuron",
        "--example",
        "memory_cell_read",
    ]
    if offline:
        command.append("--offline")
    subprocess.run(command, check=True)
    for relative, expected in identity["source_files"].items():
        if digest(Path(identity["checkout"]) / relative) != expected:
            raise ValueError(f"source changed during native compilation: {relative}")
    binary = destination / "target/debug/examples/memory_cell_read"
    if not binary.exists():
        binary = binary.with_suffix(".exe")
    receipt = {
        "schema": "hepta.memory.native-build.v1",
        "command": command,
        "binary": str(binary),
        "binary_sha256": digest(binary),
        "source_identity_sha256": digest(destination / "source-identity.json"),
        "extracted_lock_sha256": digest(destination / "Cargo.lock"),
        "rustc": subprocess.check_output(["rustc", "-vV"], text=True),
        "scope": "actual source compilation in extracted three-crate workspace; no full-product admission",
    }
    (destination / "native-build.json").write_text(
        json.dumps(receipt, indent=2, sort_keys=True) + "\n"
    )
    print(json.dumps({"binary": str(binary), "sha256": receipt["binary_sha256"]}))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root", type=Path, default=Path(__file__).resolve().parents[2]
    )
    parser.add_argument("--destination", required=True, type=Path)
    parser.add_argument("--offline", action="store_true")
    parser.add_argument("--build-example", action="store_true")
    arguments = parser.parse_args()
    destination, identity = prepare(
        arguments.root, arguments.destination, arguments.offline
    )
    if arguments.build_example:
        build_example(destination, identity, arguments.offline)


if __name__ == "__main__":
    main()
