"""Train and export a cross-language numerical regression, not language efficacy.

The bounded inventory values match the native owner fixture. Their synthetic
scope is explicit. No answer values are embedded in the serving payload.
"""

import hashlib
import json
from pathlib import Path

import numpy as np

from learned import ENCODER_PROFILE, canonical, features, predict_export, train_mlp


def main():
    root = Path(__file__).resolve().parents[2]
    output = Path(__file__).with_name("evidence") / "native-export"
    output.mkdir(parents=True, exist_ok=False)
    rows = [("item:a", [11, 3, 14]), ("item:b", [7, 2, 12])]
    texts = ["inventory policy for " + key for key, _ in rows]
    x = features(texts, 16)
    y = np.array([[float(value >> bit & 1) for value in values for bit in range(4)]
                  for _, values in rows], dtype=np.float32)
    model = train_mlp(x, y, hidden=16, steps=600, seed=120071)
    exported = model.export()
    logits = predict_export(exported, x)
    np.testing.assert_array_equal(logits > 0, y > 0)
    np.testing.assert_allclose(logits, model.predict(x), atol=1e-5, rtol=1e-5)
    supports, bank = {}, {}
    for (key, values), text, vector in zip(rows, texts, x):
        address = hashlib.sha256(key.encode()).hexdigest()
        supports[address] = [hashlib.sha256(canonical([key, values])).hexdigest()]
        raw = vector.astype("<f4").tobytes()
        bank[address] = dict(canonical_text_sha256=hashlib.sha256(text.encode()).hexdigest(),
                             feature_sha256=hashlib.sha256(raw).hexdigest(), f32le_hex=raw.hex())
    payload = dict(schema="hepta.memory.mlp-native.v12", kind="semantic",
                   address_profile="hepta.memory.frozen-feature-cache.v12",
                   numeric_profile="hepta.memory.f32-f64-relu-mlp.v12",
                   output_profile="hepta.memory.inventory-policy.bits12.v1",
                   dimension=16, hidden=16, minimum_margin=.25,
                   encoder_sha256=hashlib.sha256(canonical([ENCODER_PROFILE, 16])).hexdigest(),
                   owner_cut_sha256=hashlib.sha256(b"explicit-numerical-regression-owner").hexdigest(),
                   parameter_sha256=exported["parameter_sha256"],
                   checkpoint_sha256=hashlib.sha256(canonical(exported)).hexdigest(),
                   training_receipt_sha256=hashlib.sha256(canonical(model.receipt)).hexdigest(),
                   supports=supports, lineage_sources=sorted(value[0] for value in supports.values()),
                   features=bank, arrays=exported["arrays"])
    (output / "model.json").write_bytes(canonical(exported) + b"\n")
    (output / "payload.json").write_bytes(canonical(payload) + b"\n")
    (output / "training.json").write_bytes(canonical(dict(scope="synthetic native numerical regression",
                                                           rows=rows, texts=texts, X=x.tolist(), Y=y.tolist(),
                                                           expected_logits=logits.tolist(), receipt=model.receipt)) + b"\n")
    text = "//! Generated by qualification/memory-cell-v12/export_native.py.\n"
    text += "//! Actual Python-trained bytes; bounded synthetic inventory regression only.\n\n"
    text += 'pub const PAYLOAD: &str = r#"' + canonical(payload).decode() + '"#;\n'
    text += 'pub const EXPECTED: [[f64; 12]; 2] = ' + json.dumps(logits.tolist()) + ';\n'
    destination = root / "codex-rs/hepta-agentd/src/memory_mlp_v12_python_fixture.rs"
    destination.write_text(text)
    inventory = {p.name: {"bytes": p.stat().st_size, "sha256": hashlib.sha256(p.read_bytes()).hexdigest()}
                 for p in output.iterdir() if p.is_file()}
    (output / "INVENTORY.json").write_bytes(canonical(inventory) + b"\n")
    print(json.dumps(dict(parameter_sha256=exported["parameter_sha256"],
                          max_forward_error=float(np.max(np.abs(logits - model.predict(x)))),
                          min_margin=float(np.abs(logits).min()), fixture=str(destination))))


if __name__ == "__main__":
    main()
