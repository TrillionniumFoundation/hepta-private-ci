"""One trainable autoregressive core for four byte-level research codecs.

A neural generator, NOT a pretrained world model. Frozen Stem/connector outputs
are supplied by existing owners; no model download, production route, filesystem
or device permissions. Greedy decoding never accepts target bytes. Byte codecs
are deliberately simple and explicit; production neural codecs are not implied.
"""

from copy import deepcopy
from dataclasses import dataclass
import hashlib
import io
import math
import wave

import torch
from torch import nn
from torch.nn import functional as F

from development_ablation import PhaseClock
from development_composition import SharedCellRecurrence
from development_tensors import checked_tensor, parameter_digest


BOS, EOS, PAD = 256, 257, 258
MODALITIES = ("text", "image", "video", "audio")


@dataclass(frozen=True)
class CodecSpec:
    modality: str
    byte_count: int
    width: int = 0
    height: int = 0
    frames: int = 0
    rate: int = 0

    def validate(self):
        if (self.modality not in MODALITIES or type(self.byte_count) is not int
                or not 1 <= self.byte_count <= 1024
                or any(type(v) is not int for v in (self.width, self.height, self.frames, self.rate))):
            raise ValueError("invalid bounded codec")
        if self.modality == "text":
            valid = (self.width, self.height, self.frames, self.rate) == (0, 0, 0, 0)
        elif self.modality == "image":
            valid = (1 <= self.width <= 32 and 1 <= self.height <= 32
                     and self.byte_count == self.width * self.height and self.frames == self.rate == 0)
        elif self.modality == "video":
            valid = (1 <= self.width <= 32 and 1 <= self.height <= 32 and 2 <= self.frames <= 16
                     and 1 <= self.rate <= 60 and self.byte_count == self.width * self.height * self.frames)
        else:
            valid = (self.width == self.height == self.frames == 0 and 1000 <= self.rate <= 48000)
        if not valid:
            raise ValueError("inconsistent codec dimensions")


def decode_bytes(spec: CodecSpec, tokens: tuple[int, ...]) -> tuple[str, bytes]:
    """Render only generated bytes; no target-dependent repair or imputation.

    Text is strict UTF-8, image is PGM, video is monochrome Y4M, audio is PCM8
    WAV. This produces actual media payloads, not semantic quality evidence.
    """
    if type(spec) is not CodecSpec or type(tokens) is not tuple:
        raise ValueError("typed codec and immutable token sequence required")
    spec.validate()
    if (len(tokens) != spec.byte_count
            or any(type(t) is not int or not 0 <= t <= 255 for t in tokens)):
        raise ValueError("wrong generated length/token; no silent repair")
    raw = bytes(tokens)
    if spec.modality == "text":
        raw.decode("utf-8", errors="strict")
        return "text/plain; charset=utf-8", raw
    if spec.modality == "image":
        return "image/x-portable-graymap", f"P5\n{spec.width} {spec.height}\n255\n".encode() + raw
    if spec.modality == "video":
        header = f"YUV4MPEG2 W{spec.width} H{spec.height} F{spec.rate}:1 Ip A1:1 Cmono\n".encode()
        size = spec.width * spec.height
        return "video/x-yuv4mpeg", header + b"".join(
            b"FRAME\n" + raw[i:i+size] for i in range(0, len(raw), size))
    stream = io.BytesIO()
    with wave.open(stream, "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(1)
        wav.setframerate(spec.rate)
        wav.writeframes(raw)
    return "audio/wav", stream.getvalue()


class SharedByteGenerator(nn.Module):
    """Common GRU/readout, modality-specific lightweight scale and bias.

    width is limited to 128 and sequence length to 1025 including EOS. No input
    feature gradient flows back into the frozen Stem. Teacher forcing is only
    a training API; generate() accepts condition, modality and length, no gold.
    """

    def __init__(self, width=32, *, maximum_bytes=1024):
        super().__init__()
        if (type(width) is not int or not 4 <= width <= 128
                or type(maximum_bytes) is not int or not 1 <= maximum_bytes <= 1024):
            raise ValueError("invalid generator bounds")
        self.width, self.maximum_bytes = width, maximum_bytes
        self.recurrence = SharedCellRecurrence(width)
        self.embedding = nn.Embedding(PAD + 1, width)
        self.scale = nn.Embedding(4, width)
        self.bias = nn.Embedding(4, width)
        self.readout = nn.Linear(width, EOS + 1)
        nn.init.ones_(self.scale.weight)
        nn.init.zeros_(self.bias.weight)

    def _condition(self, condition, modality):
        checked_tensor(condition, 2, "frozen generator condition")
        if (condition.shape[1] != self.width or not 1 <= len(condition) <= 32
                or condition.dtype != self.readout.weight.dtype
                or not isinstance(modality, torch.Tensor) or modality.dtype != torch.long
                or modality.device.type != "cpu" or modality.shape != (len(condition),)
                or bool(((modality < 0) | (modality >= 4)).any())):
            raise ValueError("invalid conditioned generation batch")
        return torch.tanh(condition.detach() * self.scale(modality) + self.bias(modality))

    def forward(self, condition, modality, prefix):
        state = self._condition(condition, modality)
        if (not isinstance(prefix, torch.Tensor) or prefix.dtype != torch.long
                or prefix.device.type != "cpu" or prefix.ndim != 2
                or prefix.shape[0] != len(condition) or not 1 <= prefix.shape[1] <= self.maximum_bytes + 1
                or bool(((prefix < 0) | (prefix > PAD)).any())
                or not bool((prefix[:, 0] == BOS).all())):
            raise ValueError("invalid causal generation prefix")
        logits = []
        for t in range(prefix.shape[1]):
            state = self.recurrence.cell(self.embedding(prefix[:, t]), state)
            logits.append(self.readout(state))
        return torch.stack(logits, dim=1)

    @torch.no_grad()
    def generate(self, condition, modality, *, maximum_bytes):
        if type(maximum_bytes) is not int or not 1 <= maximum_bytes <= self.maximum_bytes:
            raise ValueError("invalid generation horizon")
        clock = PhaseClock()
        state = self._condition(condition, modality)
        previous = torch.full((len(condition),), BOS, dtype=torch.long)
        active = torch.ones(len(condition), dtype=torch.bool)
        sequences = [[] for _ in range(len(condition))]
        transitions = batches = 0
        terminated = torch.zeros(len(condition), dtype=torch.bool)
        for _ in range(maximum_bytes + 1):
            ids = active.nonzero(as_tuple=False).flatten()
            if len(ids) == 0:
                break
            next_state = self.recurrence.cell(self.embedding(previous[ids]), state[ids])
            logits = self.readout(next_state)
            if not torch.isfinite(logits).all():
                raise ValueError("nonfinite generated logits")
            # BOS is never a generated byte; EOS is learned, not injected.
            logits[:, BOS] = -torch.inf
            chosen = logits.argmax(-1)
            state[ids] = next_state
            transitions += len(ids)
            batches += 1
            for row, token in zip(ids.tolist(), chosen.tolist()):
                if token == EOS:
                    active[row] = False
                    terminated[row] = True
                elif len(sequences[row]) >= maximum_bytes:
                    active[row] = False
                else:
                    sequences[row].append(token)
                    previous[row] = token
        return {"tokens": tuple(tuple(s) for s in sequences),
                "terminated": tuple(bool(a) for a in terminated),
                "cell_transitions": transitions, "decoder_batches": batches,
                **clock.finish(), "production_authorized": False}


def fit_generator(initial, condition, modality, targets, *, steps=100, seed=17, lr=0.01):
    """Actual autoregressive next-token training on a private next snapshot."""
    initial._condition(condition, modality)
    if (type(targets) is not tuple or len(targets) != len(condition)
            or any(type(t) is not bytes or not 1 <= len(t) <= initial.maximum_bytes for t in targets)
            or type(steps) is not int or not 1 <= steps <= 1000 or type(seed) is not int
            or type(lr) not in (int, float) or not math.isfinite(lr) or not 0 < lr <= 0.1):
        raise ValueError("invalid generator training envelope")
    identity, clock = parameter_digest(initial), PhaseClock()
    out = deepcopy(initial)
    length = max(map(len, targets)) + 1
    gold = torch.full((len(targets), length), -100, dtype=torch.long)
    prefix = torch.full((len(targets), length), PAD, dtype=torch.long)
    prefix[:, 0] = BOS
    for i, target in enumerate(targets):
        gold[i, :len(target)] = torch.tensor(list(target))
        gold[i, len(target)] = EOS
        prefix[i, 1:len(target)+1] = torch.tensor(list(target))
    optimizer = torch.optim.AdamW(out.parameters(), lr=lr, weight_decay=0)
    rng = torch.Generator().manual_seed(seed)
    loss_values = []
    for _ in range(steps):
        order = torch.randperm(len(targets), generator=rng)
        logits = out(condition[order].detach(), modality[order], prefix[order])
        loss = F.cross_entropy(logits.reshape(-1, EOS + 1), gold[order].reshape(-1))
        if not torch.isfinite(loss):
            raise ValueError("nonfinite autoregressive loss")
        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        nn.utils.clip_grad_norm_(out.parameters(), 1, error_if_nonfinite=True)
        optimizer.step()
        loss_values.append(float(loss.detach()))
    out.eval()
    if parameter_digest(initial) != identity:
        raise RuntimeError("selected generator was mutated")
    if any(not torch.isfinite(p).all() for p in out.parameters()):
        raise ValueError("nonfinite generator parameters")
    return out, {**clock.finish(), "steps": steps, "initial_loss": loss_values[0],
                 "last_loss": loss_values[-1], "training_bytes": sum(map(len, targets)),
                 "teacher_forced_transitions": steps * len(targets) * length,
                 "shared_core_parameters": sum(p.numel() for p in out.recurrence.parameters()),
                 "local_modality_parameters": out.scale.weight.numel() + out.bias.weight.numel(),
                 "total_parameters": sum(p.numel() for p in out.parameters()),
                 "initial_digest": identity, "candidate_digest": parameter_digest(out),
                 "pretrained_generator": False, "production_authorized": False}


def render_generated(batch, specs):
    """Freeze generated outputs before an independent external scorer sees them."""
    if (type(batch) is not dict or type(specs) is not tuple
            or type(batch.get("tokens")) is not tuple or type(batch.get("terminated")) is not tuple
            or len(specs) != len(batch["tokens"]) or len(specs) != len(batch["terminated"])
            or not 1 <= len(specs) <= 32 or any(type(v) is not bool for v in batch["terminated"])):
        raise ValueError("unaligned generation output codecs")
    for spec in specs:
        if type(spec) is not CodecSpec:
            raise ValueError("typed codec required")
        spec.validate()
    outputs = []
    for tokens, terminated, spec in zip(batch["tokens"], batch["terminated"], specs):
        if not terminated:
            outputs.append({"status": "unterminated", "content": None})
            continue
        try:
            mime, content = decode_bytes(spec, tokens)
        except (ValueError, UnicodeError) as error:
            outputs.append({"status": "codec_rejected", "error": type(error).__name__, "content": None})
            continue
        outputs.append({"status": "generated", "mime": mime, "content": content,
                        "sha256": hashlib.sha256(content).hexdigest()})
    return tuple(outputs)
