"""Reduced graph of the original HCSN for boundary-only recurrent messages."""
import copy
from types import SimpleNamespace
import torch
import torch.nn.functional as F
from qualification.hcsn_closure_20261124.boundary_fix import delivered_boundary
from qualification.hcsn_closure_20261124.communication import control_step, initial_control


def check(model):
    c = model.config
    if c.message_mode != 'full' or c.boundary_mode != 'qvi' or c.feature_bank != 'value_risk':
        raise ValueError('Only the mixed QVI value/risk parent is supported')
    if c.precision != 'mixed' or c.feature_normalization not in ('none', 'population'):
        raise ValueError('Unsupported precision or feature scaling')
    if bool(model.synaptic_mask[:, c.neurons:].any()):
        raise ValueError('A synapse reads a channel generated by transport')


def boundary_updates(model, x):
    """Preserve original matrix widths, clock, dtypes and nominal centering."""
    c = model.config
    n, h = c.neurons, c.neurons // 2
    b = x.shape[0]
    zeros = model.reset_absolute.new_zeros(b, n)
    old = zeros
    buffered = initial_control(x[:, 0], model.control_spec)
    w = model.recurrent.weight * model.synaptic_mask
    for t, frame in enumerate(x.transpose(0, 1)):
        control, buffered, due = control_step(frame, buffered)
        prior = torch.stack((old, zeros, zeros), 1)
        message = delivered_boundary(prior, model.boundary_reference, model.boundary_mode, t)
        recurrence = F.linear(message.to(frame).flatten(1), w)
        pre = F.pad(F.linear(control, model.input_drive.weight, model.input_drive.bias), (0, h)) + recurrence
        if due:
            drift = (c.base_drift + c.drift_scale * pre.tanh()).to(model.reset_absolute)
            cost = (c.cost + c.cost_span * (model.raw_cost + .15 * pre).tanh()).to(drift)
            boundary = model.qvi_boundary(drift, cost)
        yield frame, control, pre, recurrence, drift, cost, boundary, due
        old = boundary


@torch.no_grad()
def trace(model, x):
    check(model)
    h = model.config.neurons // 2
    all_traces = {'keys': [], 'drift': [], 'preactivation': []}
    for batch in x.split(24):
        current = {k: [] for k in all_traces}
        for _, control, pre, _, drift, _, _, due in boundary_updates(model, batch):
            if due:
                current['keys'].append(F.pad(control, (0, 1), value=1.))
                current['drift'].append(drift[:, :h])
                current['preactivation'].append(pre[:, :h])
        for key, blocks in current.items():
            all_traces[key].append(torch.stack(blocks, 1))
    return {k: torch.cat(v).double() for k, v in all_traces.items()}


def features(model, x):
    """Compute readout features only; no full-network population state is returned."""
    check(model)
    c = model.config
    h = c.neurons // 2
    receiver = copy.copy(model)
    receiver._buffers = model._buffers.copy()
    receiver.reset_absolute = model.reset_absolute[h:]
    receiver._interval = {}
    initial = model.initial_state(len(x))
    density = initial.population.density[:, h:]
    old = initial.population.boundary[:, h:]
    outputs = []
    tolerance = 2e-9
    for frame, _, _, recurrence, drift, cost, boundary, due in boundary_updates(model, x):
        if due:
            # Cache uses tensor identity at fast ticks, so slice once for each new law.
            mu, k, b = drift[:, h:], cost[:, h:], boundary[:, h:]
        projected_state = SimpleNamespace(density=density, boundary=old)
        remapped, jump, _ = receiver._remap(projected_state, b)
        # External input_mark is padded with exact zeros on receivers in the full graph.
        mark = recurrence[:, h:].tanh().to(density)
        content = ((1 - c.write_fraction) * remapped[..., 1, :c.bins]
                   + c.write_fraction * mark[..., None] * remapped[..., 0, :c.bins])
        written = torch.stack((remapped[..., 0, :], torch.cat((content, remapped[..., 1, c.bins:]), -1)), -2)
        generator, event = receiver._generator(mu, b)
        density, hits, value, risk, margin = receiver._flow(written, jump, generator, event, b, k)
        if bool(((risk < -tolerance) | (risk > 1 + tolerance) | (risk > hits[..., 0] + tolerance)).any()):
            raise FloatingPointError('Receiver event invariant failed')
        if bool(((density[..., 0, :].sum(-1) - 1).abs() > tolerance).any()):
            raise FloatingPointError('Receiver mass invariant failed')
        if bool((density[..., 0, :] < -tolerance).any() or (density[..., 1, :].abs() > density[..., 0, :] + tolerance).any()):
            raise FloatingPointError('Receiver marked density invariant failed')
        bank = torch.stack((value, risk, hits[..., 1] / c.dt, hits[..., 0] / c.dt, margin), -1)
        if c.feature_normalization == 'population':
            bank = bank - bank.mean(1, keepdim=True)
            bank = bank * torch.rsqrt(bank.square().mean(1, keepdim=True) + 1e-12)
        outputs.append(bank.flatten(1).to(frame))
        old = b
    return torch.stack(outputs, 1).flatten(1)


def score(model, ridge, x):
    z = features(model, x).double()
    return ((z - ridge['mean']) / ridge['scale']) @ ridge['weight'] + ridge['bias']


@torch.no_grad()
def scores(model, c, x):
    return torch.cat([score(model, c['ridge'], b) for b in x.split(24)])
