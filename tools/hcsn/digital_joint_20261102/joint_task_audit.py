def fixture():
    return dict(schema=task.SCHEMA, id="joint-semantic-fixture", deadline=6, initial_budget=3,
                target_tick=6, prior_distance=.375, duration=[.25, .5, .75, 1., .5, .25],
                drive=[1, -1, 1, -1, 1, -1], reliability=[.7, .8, .7, .8, .7, .8],
                read_price=[.1]*6, read_delay=[2, 1, 2, 1, 2, 1], latency_price=.01,
                repair_price=.03, failure_probability=.1,
                packets=[f"boundary_{i}.json" for i in range(1, 7)], packet_sha256=["0"*64]*6)


class TwoStateLaw:
    u = np.array([-1., 1.]); positive = u > 0

    def __init__(self, rate=.7):
        self.rate = rate

    def initial_mass(self, distance):
        return np.array([.5, .5])

    def transition(self, dt, drive):
        same = .5+.5*np.exp(-2*self.rate*dt)
        return np.array([[same, 1-same], [1-same, same]])

    def emission(self, r, confusion):
        return np.array([[r, 1-r], [1-r, r]]) @ confusion


def enumerate_target(public, law, confusion, observations):
    """Sum all 2^7 hidden trajectories, never calling task.Oracle."""
    total = positive = 0.
    for path in itertools.product((0, 1), repeat=7):
        weight = .5
        for t in range(6):
            weight *= law.transition(public["duration"][t], public["drive"][t])[path[t], path[t+1]]
        for tick, y in observations.items():
            weight *= law.emission(public["reliability"][tick-1], confusion)[path[tick], y]
        total += weight
        positive += weight*path[6]
    return positive/total


def main():
    wall, cpu = time.perf_counter(), time.process_time(); checks = []
    public = fixture(); law = TwoStateLaw(); confusion = np.array([[.97, .03], [.04, .96]])
    oracle = task.Oracle(public, law, confusion); errors = []
    for tick, pairs in ((0, []), (1, [(1, 0)]), (2, [(2, 1)]), (4, [(2, 0), (4, 1)]), (6, [(1, 1), (3, 0), (6, 1)])):
        state = task.initial(public); state["tick"] = tick
        state["history"] = [dict(source_tick=max(0, t-2), observation_tick=t, observation=y,
                                  reliability=public["reliability"][t-1]) for t, y in pairs]
        expected = enumerate_target(public, law, confusion, dict(pairs))
        errors.append(abs(oracle.posterior(state)-expected))
        q = oracle.q(state)
        assert abs(q[4]-(1-2*expected)) < 1e-12 and abs(q[5]-(2*expected-1)) < 1e-12
    assert max(errors) < 2e-14; checks.append("deadline target agrees with 128-path enumeration")
    p = fixture(); p.update(reliability=[1.]*6, failure_probability=0., latency_price=0., read_delay=[1]*6)
    static = task.Oracle(p, TwoStateLaw(0.), np.array([[.99, .01], [.01, .99]]))
    q = static.q(task.initial(p)); assert abs(q[2]-.88) < 1e-12 and abs(q[1]-.88) < 1e-12
    checks.append("independent one-read value .88 and free-WAIT .88")

    class RecordingAdapter:
        def __init__(self): self.opens = []
        def read(self, path):
            self.opens.append(Path(path).name); raw = Path(path).read_bytes()
            return dict(observation=json.loads(raw)["observation"], payload_sha256=hashlib.sha256(raw).hexdigest())

    with tempfile.TemporaryDirectory(prefix="joint-task-fixture-") as temp:
        directory = Path(temp); p = fixture(); p["reliability"] = [.99]*6
        for i, name in enumerate(p["packets"]):
            payload = json.dumps(dict(observation=i % 2)).encode()
            p["packet_sha256"][i] = hashlib.sha256(payload).hexdigest()
            if i != 3: (directory/name).write_bytes(payload)
        adapter = RecordingAdapter(); owner = task.Owner(p, directory, adapter)
        first = owner.step(2); assert not adapter.opens and first["completion"] is None
        second = owner.step(1)
        assert adapter.opens == ["boundary_2.json"] and second["completion"] == dict(observation=1, observation_tick=2)
        assert owner.state["history"][0]["source_tick"] == 0 and owner.state["history"][0]["observation_tick"] == 2
        assert task.history_features(owner.state)[1] == 1 and task.history_features(owner.state)[0] == 0
        checks.append("delay-two reads current boundary2 only, no pre-due content")
        owner.step(2); owner.step(1)
        assert owner.state["broken"] and owner.state["tick"] == 4
        old = deepcopy(owner.state); opens = list(adapter.opens)
        try: owner.step(2)
        except ValueError: pass
        else: raise AssertionError("illegal READ accepted while broken")
        assert owner.state == old and adapter.opens == opens
        owner.step(3); assert not owner.state["broken"] and owner.state["tick"] == 5
        checks.append("missing due packet is charged and enters broken; repair and illegal action atomic")
        owner.step(2); assert owner.state["tick"] == 6
        owner.step(5)
        target = task.evaluate_terminal(owner.state, 1)
        assert target["utility"] == 1-owner.state["charges"] and target["reads_requested"] == 3
        assert abs(owner.state["charges"]-(3*.1+.03+.01*sum(p["duration"]))) < 1e-14
        checks.append("fixed evaluator target and complete fees")
        cancelled = task.Owner(p, directory, RecordingAdapter()); cancelled.step(2); cancelled.step(0)
        assert cancelled.state["pending"] is None and not cancelled.adapter.opens
        checks.append("STOP cancels pending without opening its future packet")
    np_law = IndependentLaw(np.array([.2, -.1, .3, -.2, .2, -.1, .4, -.3]))
    generator_errors = []
    for drive in (-1, 0, 1):
        q = np_law.generator(drive)
        assert np.min(q-np.diag(np.diag(q))) >= 0
        generator_errors.append(float(np.max(np.abs(q.sum(1)))))
        for dt in (.25, .75, 1.5):
            t = np_law.transition(dt, drive)
            assert t.min() >= 0 and np.max(np.abs(t.sum(1)-1)) < 2e-11
    for distance in (.125, .375, .75):
        prior = np_law.initial_mass(distance)
        assert prior.sum() == 1 and prior[np_law.positive].sum() == .5
    checks.append("independent CTMC conservation, positivity and nondegenerate public priors")
    result = dict(schema="joint-task-prefit-semantic-audit-v1", passed=True, checks=checks,
                  path_enumeration_max_error=max(errors), generator_row_error=max(generator_errors),
                  world_cohorts_generated=0, wall_seconds=time.perf_counter()-wall,
                  cpu_seconds=time.process_time()-cpu,
                  source_sha256={name:hashlib.sha256((Path(__file__).parent/name).read_bytes()).hexdigest()
                                 for name in ("joint_law.py", "joint_task.py", "joint_data.py", "joint_task_audit.py")})
    output = Path(__file__).parent/"evidence/joint_task_prefit_audit.json"
    output.parent.mkdir(exist_ok=True); output.write_text(json.dumps(result, indent=2, sort_keys=True)+"\n")
    print(json.dumps(result, sort_keys=True))


if __name__ == "__main__":
    main()
