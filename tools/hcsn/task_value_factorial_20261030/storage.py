"""Exclusive, deterministic evidence writes and source identity."""
import gzip
import hashlib
import json
from pathlib import Path
import platform
import resource
import shutil
import tarfile

import numpy as np
import scipy

from .task import HERE, sha


def packed(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    data = json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()
    with path.open("xb") as stream:
        stream.write(gzip.compress(data, mtime=0))
    return sha(path)


def unpack(path):
    return json.loads(gzip.decompress(Path(path).read_bytes()))


def archive(path, root):
    """Preserve actual generated bytes for independent replay, no symlinks."""
    path, root = Path(path), Path(root)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("xb") as stream:
        with gzip.GzipFile(fileobj=stream, mode="wb", mtime=0) as compressed:
            with tarfile.open(fileobj=compressed, mode="w") as tar:
                for file in sorted(root.rglob("*")):
                    if file.is_file() and not file.is_symlink():
                        info = tar.gettarinfo(str(file), str(file.relative_to(root)))
                        info.uid = info.gid = info.mtime = 0
                        info.uname = info.gname = ""
                        with file.open("rb") as source:
                            tar.addfile(info, source)
    # The workspace can be small. Verify every archived byte before removing
    # only this run's generated working copy; the archive remains authoritative.
    with tarfile.open(path, "r:gz") as tar:
        for member in tar.getmembers():
            original = root/member.name
            restored = tar.extractfile(member).read()
            if hashlib.sha256(restored).hexdigest() != sha(original):
                raise ValueError(("Archive verification failed", member.name))
    if root.parent.name != "_work":
        raise ValueError("Refuse to retire anything outside this run's _work child")
    shutil.rmtree(root)
    return sha(path)


def source_identity():
    paths = sorted(HERE.glob("*.py"))+[HERE/"PROTOCOL.json", HERE/"UPSTREAM_FILES.json"]
    files = {path.name: sha(path) for path in paths}
    encoded = json.dumps(files, sort_keys=True).encode()
    return dict(files=files, sha256=hashlib.sha256(encoded).hexdigest())


