"""Independent visible-consistent completion enumeration on train-only draws.

Expected distributions are counted from explicit possible hidden completions,
not from the candidate's case formulas or scorer availability flags.
"""
import hashlib
import itertools
import json
from pathlib import Path
import time

import numpy as np

from experiments.hcsn_addressed_flow_20261101 import data
from experiments.hcsn_four_stage_flow_20261031.extended_eval import stress_data
from .posterior import VisiblePosterior

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]


def sha(path): return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def arrays(task,condition):
    base=data.batch(task,32,423091,'train','missing' if condition.startswith('missing') else 'base')
    if condition.endswith('tokens_128'):
        return stress_data(task,base,'long_tokens_128')
    return base


def completions(task,x,observed):
    """Enumerate worlds satisfying the supplied public finite generator law."""
    offset=4 if task=='binding' else 0
    initial={}; updates={}; aliases={}; erased=[]
    for t in range(offset+8+(2 if task=='selective' else 0)):
        if not observed[t]:
            erased.append(t); continue
        e=x[t]; kind=int(e[12:16].argmax())
        if kind==3:
            aliases[int(e[19:23].argmax())]=int(e[:4].argmax())
        elif kind==0:
            key=int(e[:4].argmax()); value=int(e[4:12].argmax())
            (initial if t<offset+8 else updates)[key]=value
    assert len(erased)<=1
    if not erased:
        final=initial.copy();final.update(updates)
        return [final],aliases
    visible_values=set(initial.values())|set(updates.values())
    unseen=sorted(set(range(8))-visible_values)
    worlds=[]
    if erased[0]<offset+8:
        missing_key=next(iter(set(range(4))-set(initial)))
        for value in unseen:
            final=initial.copy();final[missing_key]=value;final.update(updates)
            worlds.append(final)
    else:
        for key in sorted(set(range(4))-set(updates)):
            for value in unseen:
                final=initial.copy();final.update(updates);final[key]=value
                worlds.append(final)
    assert worlds
    return worlds,aliases


def expected_probabilities(task,a):
    result=np.zeros((len(a['x']),4,8))
    cardinalities=[]
    for row in range(len(a['x'])):
        worlds,aliases=completions(task,a['x'][row],a['observed'][row])
        cardinalities.append(len(worlds))
        for slot,t in enumerate(range(a['x'].shape[1]-4,a['x'].shape[1])):
            event=a['x'][row,t]
            key=aliases[int(event[19:23].argmax())] if task=='binding' else int(event[:4].argmax())
            for world in worlds: result[row,slot,world[key]]+=1/len(worlds)
    return result,cardinalities


def main():
    start=time.process_time(); rows=[]; query_checks=0; permutation_checks=0
    for task in ('mqar','selective','binding'):
        for condition in ('base','missing','long_tokens_128','missing_tokens_128'):
            a=arrays(task,condition); model=VisiblePosterior(task)
            prediction=model.forward(a['x'],a['dt'],a['observed'])
            expected,cardinality=expected_probabilities(task,a)
            error=float(np.abs(prediction['probabilities'][:,-4:]-expected).max())
            assert error<1e-14
            # A label generated by any compatible world must have nonzero mass.
            labels=a['y'][:,-4:]
            assert np.all(np.take_along_axis(expected,labels[...,None],axis=-1)>0)
            # Reordering current/future queries changes no visible memory state;
            # each keyed posterior and acceptance decision must follow its query.
            for order in itertools.permutations(range(4)):
                modified=a['x'].copy();modified[:,-4:]=a['x'][:,-4:][:,order]
                alternative=model.forward(modified,a['dt'],a['observed'])
                assert np.array_equal(alternative['probabilities'][:,-4:],prediction['probabilities'][:,-4:][:,order])
                assert np.array_equal(alternative['accepted'][:,-4:],prediction['accepted'][:,-4:][:,order])
                permutation_checks+=1
            alternative=model.forward(a['x'],a['dt']*7+0.03125,a['observed'])
            for key in prediction: assert np.array_equal(alternative[key],prediction[key])
            query_checks+=expected.shape[0]*4
            rows.append(dict(task=task,condition=condition,episodes=len(a['x']),query_checks=expected.shape[0]*4,
                             max_posterior_error=error,hidden_completion_counts=sorted(set(cardinality)),
                             all_query_permutations=24,clock_invariance=True))
    unsupported=[]
    for task in ('mqar','selective','binding'):
        a=data.batch(task,8,423103,'train','resample')
        try: VisiblePosterior(task).forward(a['x'],a['dt'],a['observed'])
        except ValueError: unsupported.append(dict(task=task,case='resample',correctly_rejected=True))
        else: raise AssertionError('Resample must not be silently accepted under the one-erasure contract')
        a=data.batch(task,8,423107,'train','base')
        for row in range(len(a['x'])):
            writes=np.flatnonzero(a['x'][row,:,12]==1)[:2]
            a['x'][row,writes]=0;a['observed'][row,writes]=False
        try: VisiblePosterior(task).forward(a['x'],a['dt'],a['observed'])
        except ValueError: unsupported.append(dict(task=task,case='two_erasures',correctly_rejected=True))
        else: raise AssertionError('Multiple erasures must not be silently accepted')
    candidate_path=HERE/'results/run001/CANDIDATE.json'
    candidate=json.loads(candidate_path.read_text())
    with np.load(HERE/'results/run001/TRAIN_RAW.npz',allow_pickle=False) as z:
        episode=z['episode'];equal=z['labels']==z['visible_old']
        assert len(equal)==candidate['ambiguous_queries'] and int(equal.sum())==candidate['retained']
        assert len(equal)==3*len(np.unique(episode))
        for key in np.unique(episode): assert int(equal[episode==key].sum())==2
    assert candidate['q']==(candidate['retained']+.5)/(candidate['ambiguous_queries']+1)
    result=dict(schema='hcsn.missing-r2.independent-completion-audit.v1',passed=True,
                scope='Train-only source-law enumeration and invariance, not a new confirmation or learned-neural reliability certificate',
                rows=rows,query_checks=query_checks,query_permutation_batches=permutation_checks,
                unsupported_inputs=unsupported,completion_reference='Equal-count explicit possible missing key/value assignments consistent with public without-replacement law and visible prefix',
                estimated_q=candidate['q'],exact_q=2/3,
                q_fit_interpretation='Each erased-final episode contributes exactly three correlated ambiguous queries, exactly two retained old values; the ratio is deterministic smoothing, not independent-binomial inference',
                candidate_sha256=sha(candidate_path),source_sha256={str(p.relative_to(ROOT)):sha(p) for p in
                  [Path(__file__),HERE/'posterior.py',ROOT/'experiments/hcsn_addressed_flow_20261101/data.py',
                   ROOT/'experiments/hcsn_four_stage_flow_20261031/synthetic_data.py',ROOT/'experiments/hcsn_four_stage_flow_20261031/extended_eval.py']},
                cpu_seconds=time.process_time()-start,all_blockers_closed=False,production_activation=False)
    with (HERE/'AUDIT_LAW.json').open('x') as stream:
        json.dump(result,stream,indent=2,sort_keys=True,allow_nan=False);stream.write('\n')
    print(json.dumps(dict(passed=True,query_checks=query_checks,query_permutation_batches=permutation_checks,unsupported_checks=len(unsupported)),sort_keys=True))


if __name__=='__main__': main()
