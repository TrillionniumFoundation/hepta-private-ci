"""Exact-rational pointwise debt-PDE error comparison, no whole-domain claim.

A separate Brownian physical-time first-hit oracle provides rigorous rational
bounds on the TRUE fixed-barrier financial bond at selected log-grid nodes.
Compare exact binary64 output values of historical BE and alternative
Rannacher-CN by interval distance. A pointwise strict improvement is proven
ONLY when the Rannacher upper error lies below the BE lower error.

No global error bound, PDE time/space continuum theorem, admissible financial
free-boundary certificate, FP32/BF16 or production admission is established.
"""
from dataclasses import dataclass
from fractions import Fraction as F
import hashlib
import json
import math

from .hx_bond_pde_independent import solve_bond_pde
from .hx_bond_pde_rannacher import solve_bond_rannacher,UnresolvedRannacher
from .first_hit_time_interval import (bound_first_hit,
    financial_bond_from_hit_interval,UnresolvedFirstHit)


@dataclass(frozen=True)
class CertifiedNodeComparison:
    physical_identity_sha256: str
    nodes: int
    time_steps: int
    index: int
    log_state_float_hex: str
    true_price_lower: str
    true_price_upper: str
    be_error_lower: str
    be_error_upper: str
    rannacher_error_lower: str
    rannacher_error_upper: str
    guaranteed_pointwise_improvement: bool
    first_hit_cells: int
    research_only: bool = True
    global_financial_obstacle_certified: bool = False
    all_node_financial_error_certified: bool = False
    production_activation: bool = False


def _identity(p,barrier,log_upper,nodes,time_steps):
    fields=('rate','payout','volatility','maturity','principal','coupon',
            'tax_shield','recovery','shock_intensity','sale_fraction')
    vals={k:float(getattr(p,k)).hex() for k in fields}
    vals.update(barrier=float(barrier).hex(),log_upper=float(log_upper).hex(),
                nodes=nodes,time_steps=time_steps,
                method='pointwise BE vs Rannacher-CN, physical HX f64')
    return hashlib.sha256(json.dumps(vals,sort_keys=True,separators=(',',':')).encode()).hexdigest()


def _distance(x,lo,hi):
    return max(F(0),lo-x,x-hi),max(abs(x-lo),abs(x-hi))


def certify_debt_node(p,barrier:float,*,nodes:int,time_steps:int,index:int,
                      log_upper:float=3.6,tolerance:str='0.000002',
                      max_cells:int=50000)->CertifiedNodeComparison:
    if type(nodes) is not int or type(index) is not int or not 1<=index<nodes-1:
        raise UnresolvedRannacher('require strict interior financial index')
    if not (type(tolerance) is str and type(max_cells) is int):
        raise UnresolvedRannacher('invalid exact oracle budget')
    old=solve_bond_pde(p,barrier,nodes=nodes,time_steps=time_steps,
                       log_upper=log_upper)
    candidate=solve_bond_rannacher(p,barrier,nodes=nodes,time_steps=time_steps,
                                   log_upper=log_upper)
    # The finite grid coordinates are exactly the binary64 values generated by
    # the two PDE solvers; no transformation to algebraic Eq.(8) is performed.
    y=float(index*(log_upper/(nodes-1)))
    fr=F.from_float
    mu=fr(p.rate)-fr(p.payout)-fr(p.volatility)**2/2
    discount=fr(p.rate)+fr(p.shock_intensity)*fr(p.sale_fraction)
    try:
        hit=bound_first_hit(distance=fr(y),drift=mu,
                            diffusion=fr(p.volatility),
                            maturity=fr(p.maturity),discount=discount,
                            tolerance=tolerance,max_cells=max_cells)
        lo,hi=financial_bond_from_hit_interval(first=hit,rate=fr(p.rate),
                     maturity=fr(p.maturity),principal=fr(p.principal),
                     coupon=fr(p.coupon),shock_intensity=fr(p.shock_intensity),
                     sale_fraction=fr(p.sale_fraction),recovery=fr(p.recovery),
                     boundary=fr(barrier))
    except UnresolvedFirstHit as err:
        raise UnresolvedRannacher('exact time-domain oracle refused') from err
    if not 0<=lo<=hi:
        raise UnresolvedRannacher('invalid certified physical-price interval')
    old_lo,old_hi=_distance(fr(old.values[index]),lo,hi)
    cand_lo,cand_hi=_distance(fr(candidate.values[index]),lo,hi)
    return CertifiedNodeComparison(_identity(p,barrier,log_upper,nodes,time_steps),
          nodes,time_steps,index,y.hex(),str(lo),str(hi),str(old_lo),str(old_hi),
          str(cand_lo),str(cand_hi),cand_hi<old_lo,hit.cells)
