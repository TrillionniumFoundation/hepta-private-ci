class ExpCdfUnderflowTests(unittest.TestCase):
    def test_old_cutoff_and_true_underflow_nextafter(self):
        for exponent,argument,expected in HELPER:
            with self.subTest(exponent=exponent,argument=argument):
                self.assertEqual(_exp_cdf(exponent,argument),expected)

    def test_positive_minimum_tail_is_not_erased(self):
        self.assertEqual(_exp_cdf(math.nextafter(-745.,-math.inf),math.inf),math.ulp(0.))
        self.assertEqual(_exp_cdf(-745.1,math.inf),math.ulp(0.))
        self.assertEqual(_exp_cdf(-746.,math.inf),0.)
        self.assertEqual(_exp_cdf(-math.inf,0.),0.)
        self.assertEqual(_exp_cdf(0.,-math.inf),0.)

    def test_positive_side_overflow_policy_is_unchanged(self):
        self.assertEqual(_exp_cdf(709.,math.inf),math.exp(709.))
        for exponent in (math.nextafter(709.,math.inf),710.,math.inf):
            with self.subTest(exponent=exponent):
                with self.assertRaises(OverflowError):
                    _exp_cdf(exponent,math.inf)

    def test_real_density_extreme_grid_and_zero_coupon(self):
        for params,v,tau,expected_f,expected_g in REAL:
            with self.subTest(params=params,v=v):
                p=HX(**params)
                f,g=_first_passage_factors(p,v,tau)
                self.assertTrue(0<=g<=f<=1)
                self.assertLessEqual(abs(f-expected_f),math.ulp(0.))
                self.assertLessEqual(abs(g-expected_g),math.ulp(0.))
                ordinary=bond_value(p,math.exp(v),tau,1.)
                direct=bond_value(p,math.exp(v),tau,1.,direct_coupon_survival=True)
                self.assertEqual(ordinary,direct)
                self.assertTrue(math.isfinite(ordinary))
