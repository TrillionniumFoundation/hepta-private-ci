"""Exact-rational *upper bound* for the upper-boundary debt truncation in HX.

This module certifies one narrow error component, NOT the total error of the
HX financial bond PDE and NOT the coupled-equity obstacle. Inputs are
interpreted as exact binary64 physical parameters, not mathematical decimal
idealizations. The proof is a nonnegative exponential-martingale argument;
the exponential bound is made rational using exp(x) >= sum(x**k/k!).

For Y_t = y + mu*t + sigma*W_t and a>0, each lambda>0 gives
 P(sup_{0<=s<=T}(Y_s-y)>=a) <= exp(-lambda*a + T*max(psi,0)),
 psi=lambda*mu + lambda**2*sigma**2/2.
For x>=0, exp(-x) <= 1 / sum_{k=0}^N x**k/k! exactly.

For a representative HX bond, U(t) is the never-default bond value.
At default, recovery R_b replaces U(t_remaining), so the discrepancy at
upper log-boundary L is bounded by C*P_L(first-hit lower 0 by T), with
 C=max(|R_b - par|, |R_b - coupon/q|).
The resulting uniform bound covers the *continuum upper truncation error*
for the fixed financial barrier, NOT the time/space/roundoff PDE errors.
"""
from dataclasses import dataclass
from fractions import Fraction
import math


class UnresolvedTailCertificate(ValueError):
    """Reject invalid or unsupported certification inputs."""


def _f64(x, name: str) -> Fraction:
    if type(x) not in (float, int):
        raise UnresolvedTailCertificate(f'{name}: binary64 number required')
    try:
        y = float(x)
    except (OverflowError, ValueError) as e:
        raise UnresolvedTailCertificate(f'{name}: unrepresentable') from e
    if not math.isfinite(y) or (type(x) is int and int(y) != x):
        raise UnresolvedTailCertificate(f'{name}: nonfinite or inexact integer')
    return Fraction.from_float(y)


def _exp_minus_upper(x: Fraction, terms: int) -> Fraction:
    if not isinstance(x, Fraction) or x < 0:
        raise UnresolvedTailCertificate('negative exponential certificate exponent')
    if type(terms) is not int or not 16 <= terms <= 256:
        raise UnresolvedTailCertificate('invalid Taylor resource budget')
    summation = Fraction(1)
    term = Fraction(1)
    for k in range(1, terms + 1):
        term = term*x/k
        summation += term
    return Fraction(1)/summation


def _doob_probability(*, drift: Fraction, diffusion: Fraction,
                      duration: Fraction, distance: Fraction,
                      terms: int = 128) -> tuple[Fraction, Fraction]:
    """Return exact rational probability ceiling and chosen exponent.

    Choose from the positive Chernoff stationary lambda, the drift-zero
    martingale lambda, and a parameter-independent positive trial.
    Lambda selection is optional: every positive choice gives a bound.
    """
    if not (diffusion > 0 and duration > 0 and distance > 0):
        raise UnresolvedTailCertificate('positive sigma, duration and gap required')
    variance = diffusion*diffusion
    candidates = [distance/(variance*duration)]
    optimum = (distance/duration-drift)/variance
    if optimum > 0:
        candidates.append(optimum)
    if drift < 0:
        candidates.append(-2*drift/variance)
    x = max((lam*distance-duration*max(Fraction(0),lam*drift+variance*lam*lam/2))
            for lam in candidates)
    if x <= 0:
        return Fraction(1),Fraction(0)
    if x.numerator.bit_length() + x.denominator.bit_length() > 4096:
        raise UnresolvedTailCertificate('Taylor exponent exceeds exact arithmetic budget')
    return _exp_minus_upper(x,terms), x


def _power10(k: int) -> Fraction:
    return Fraction(10**k) if k>=0 else Fraction(1,10**(-k))


def ceil_decimal_string(value: Fraction, *, digits: int = 12,
                        floor_exponent: int = -45) -> str:
    """Exact outward decimal rounding, with a conservative tiny-value floor."""
    if not isinstance(value,Fraction) or value < 0:
        raise UnresolvedTailCertificate('nonnegative rational bound required')
    if type(digits) is not int or not (4<=digits<=30):
        raise UnresolvedTailCertificate('unsupported decimal precision')
    if type(floor_exponent) is not int or not (-50<=floor_exponent<=-4):
        raise UnresolvedTailCertificate('unsupported decimal floor')
    if value == 0:
        return '0'
    if value <= _power10(floor_exponent):
        return f'1e{floor_exponent}'
    # bit_length avoids Python's >4300-decimal-digit int string conversion
    # limit for the exact Fractions generated by 128 Taylor terms.
    k = int((value.numerator.bit_length() - value.denominator.bit_length())
            * 0.3010299956639812)
    while value < _power10(k):
        k -= 1
    while value >= _power10(k+1):
        k += 1
    if k > 45:
        raise UnresolvedTailCertificate('certified bound exceeds budget domain')
    offset=digits-1-k
    scaled=value*_power10(offset)
    integer=(scaled.numerator+scaled.denominator-1)//scaled.denominator
    if integer >= 10**digits:
        return f'1e{k+1}'
    return f'{integer}e{k-digits+1}'


def floor_decimal_string(value: Fraction, *, digits: int = 12) -> str:
    """Exact downward rounding of a nonnegative Chernoff exponent."""
    if not isinstance(value, Fraction) or value < 0:
        raise UnresolvedTailCertificate('invalid nonnegative exponent')
    if type(digits) is not int or not (4 <= digits <= 30):
        raise UnresolvedTailCertificate('invalid exponent display precision')
    if value == 0:
        return '0'
    k = int((value.numerator.bit_length() - value.denominator.bit_length())
            * 0.3010299956639812)
    while value < _power10(k):
        k -= 1
    while value >= _power10(k+1):
        k += 1
    if k > 45:
        raise UnresolvedTailCertificate('exponent display exceeds budget domain')
    offset = digits-1-k
    scaled = value*_power10(offset)
    integer = scaled.numerator//scaled.denominator
    return f'{integer}e{k-digits+1}'


@dataclass(frozen=True)
class HXSpatialTailCertificate:
    lower_hit_probability_bound: str
    uniform_debt_spatial_error_bound: str
    local_debt_spatial_error_bound: str
    upper_hit_probability_bound: str
    monetary_default_replacement_ceiling: str
    lower_hit_chernoff_exponent: str
    upper_hit_chernoff_exponent: str
    taylor_terms: int
    parameter_semantics: str = 'exact binary64 physical inputs, fixed financial barrier'
    covers: tuple[str,...] = ('continuum upper spatial Dirichlet truncation',)
    uncovered: tuple[str,...] = (
        'spatial derivative discretization', 'time stepping',
        'coefficient rounding', 'financial upper equity boundary',
        'global coupled equilibrium', 'real model parameter uncertainty')
    debt_error_budget_complete: bool = False
    scientific_gate_closed: bool = False
    production_activation: bool = False

    def to_total_pde_error_budget(self) -> str:
        raise UnresolvedTailCertificate(
            'spatial-tail bound cannot be substituted for complete PDE debt error')


def certified_hx_bond_spatial_tail(p, candidate_barrier: float,
                                  *, log_upper: float, log_state: float = 0.0,
                                  duration: float | None = None,
                                  taylor_terms: int = 128) -> HXSpatialTailCertificate:
    """Conditional on *fixed barrier*, rigorously bound debt far-field truncation.

    No call to HX equations, quadrature, PDE solver, QVI, or SciPy. A small
    exact-rational sup bound can be converted to a decimal error **component**
    for an external ledger, but must NOT be passed to the conditional debt
    gate as the *total* error budget.
    """
    fields = ('rate','payout','volatility','maturity','principal','coupon',
              'tax_shield','recovery','shock_intensity','sale_fraction')
    try:
        a={field:_f64(getattr(p,field),field) for field in fields}
    except (AttributeError,TypeError) as e:
        raise UnresolvedTailCertificate('missing HX financial parameters') from e
    if not (a['rate']>0 and a['payout']>=0 and a['volatility']>0
            and a['maturity']>0 and a['principal']>0 and a['coupon']>=0
            and a['shock_intensity']>=0 and 0<=a['sale_fraction']<=1
            and 0<=a['recovery']<=1 and 0<=a['tax_shield']<=1):
        raise UnresolvedTailCertificate('invalid HX structural domain')
    b=_f64(candidate_barrier,'candidate_barrier')
    L=_f64(log_upper,'log_upper')
    y=_f64(log_state,'log_state')
    T=a['maturity'] if duration is None else _f64(duration,'duration')
    if not (b>0 and 0<=y<L<=12 and T>0 and T<=a['maturity']):
        raise UnresolvedTailCertificate('unsupported barrier/log-asset/duration')
    q=a['rate']+a['shock_intensity']*a['sale_fraction']
    base=a['coupon']/(a['maturity']*q)
    par=a['principal']/a['maturity']
    recovery=a['recovery']*b/a['maturity']
    C=max(abs(recovery-par),abs(recovery-base))
    drift=a['rate']-a['payout']-a['volatility']**2/2
    p_down,down_x=_doob_probability(drift=-drift,
           diffusion=a['volatility'],duration=T,distance=L,terms=taylor_terms)
    p_up,up_x=_doob_probability(drift=drift,
           diffusion=a['volatility'],duration=T,distance=L-y,terms=taylor_terms)
    uniform = C*p_down
    local = uniform*p_up
    return HXSpatialTailCertificate(
        ceil_decimal_string(p_down),ceil_decimal_string(uniform),
        ceil_decimal_string(local),ceil_decimal_string(p_up),
        ceil_decimal_string(C),floor_decimal_string(down_x),
        floor_decimal_string(up_x),taylor_terms)
