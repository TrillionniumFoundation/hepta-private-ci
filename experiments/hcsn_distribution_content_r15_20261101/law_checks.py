"""Independent finite-law, content-moment, gradient and causal checks.

No task confirmation observations are read or generated by this module.
"""

import argparse
import json
import math
from pathlib import Path
import time

import numpy as np
from scipy.linalg import expm
from scipy.special import log_ndtr
import torch

from experiments.hcsn_validation_r14_20261101.numerics.zero_delay import ZeroDelayFlow
from .law_core import DistributionContentCore


def run():
    torch.set_num_threads(1)
    torch.manual_seed(150903)
    begin = time.process_time()
    records, continuum = [], []

    def check(name, value, tolerance, relation="le"):
        if isinstance(value, torch.Tensor):
            value = value.detach()
        value = float(value)
        passed = value <= tolerance if relation == "le" else value >= tolerance
        records.append(dict(name=name, value=value, tolerance=tolerance,
                            relation=relation, passed=bool(passed and math.isfinite(value))))

    core = DistributionContentCore(seed=150903).double()
    n, size = core.n_positions, core.n_positions+1
    for family in core.FAMILIES:
        model = DistributionContentCore(family=family, seed=150903).double()
        q = model.generator if family == "analytic_distribution" else model.ordinary_generator
        a = q.numpy()
        generator_scale = np.finfo(np.float64).eps*max(1., np.abs(a).sum(0).max())
        check(f"{family}.generator_mass_scaled_roundoff", np.abs(a.sum(0)).max()/generator_scale, 4.)
        check(f"{family}.generator_positive", np.minimum(a-np.diag(np.diag(a)), 0).min(), -1e-14, "ge")
        initial = model.initial_state(3, dtype=torch.float64)
        raw = torch.rand(3, size, dtype=torch.float64)
        initial["probability"] = raw/raw.sum(-1, keepdim=True)
        initial["content_moment"] = initial["probability"][..., None]*torch.tanh(torch.randn(3, size, 16, dtype=torch.float64))
        for horizon in (0., .25, .7, 1., 1.75, 4., 40.):
            got = model.propagate(initial, torch.tensor(horizon, dtype=torch.float64))
            p = initial["probability"].numpy()@expm(a*horizon).T
            m = np.einsum("ij,bjk->bik", expm(a*horizon), initial["content_moment"].numpy())
            check(f"{family}.{horizon}.scipy_probability", np.max(np.abs(got["probability"].numpy()-p)), 2e-12)
            check(f"{family}.{horizon}.scipy_moment", np.max(np.abs(got["content_moment"].numpy()-m)), 2e-12)
            check(f"{family}.{horizon}.mass", (got["probability"].sum(-1)-1).abs().max(), 2e-12)
            check(f"{family}.{horizon}.positivity", got["probability"].min(), -2e-14, "ge")
        split = model.propagate(model.propagate(initial, torch.tensor(.3, dtype=torch.float64)), torch.tensor(.7, dtype=torch.float64))
        whole = model.propagate(initial, torch.tensor(1., dtype=torch.float64))
        for field in initial:
            check(f"{family}.partition.{field}", (split[field]-whole[field]).abs().max(), 2e-12)
        observed = model.observe(whole, 1e3*torch.randn(3, 16, dtype=torch.float64))
        check(f"{family}.observation_mass", (observed["probability"].sum(-1)-1).abs().max(), 2e-12)
        check(f"{family}.observation_loss_unchanged", (observed["probability"][:, -1]-whole["probability"][:, -1]).abs().max(), 0.)
        check(f"{family}.conditional_content_bound", (observed["content_moment"].abs()-observed["probability"][..., None]).max(), 2e-12)
        collapsed = model.collapse(whole, "content_independence")
        check(f"{family}.collapse_probability", (collapsed["probability"]-whole["probability"]).abs().max(), 0.)
        check(f"{family}.collapse_content_mean", (collapsed["content_moment"].sum(1)-whole["content_moment"].sum(1)).abs().max(), 2e-12)
        reduced = model.collapse(whole, "mean_position")
        check(f"{family}.collapse_position_mean", ((reduced["probability"][:, :-1]-whole["probability"][:, :-1])*model.positions).sum(-1).abs().max(), 2e-12)
        # Independence changes a weighted current readout: report this boundary.
        check(f"{family}.collapse_can_change_current_readout", (model.read_state(collapsed)-model.read_state(whole)).abs().max().detach(), 1e-7, "ge")
        preserved = model.collapse(whole, "readout_independence")
        check(f"{family}.readout_independence.current_feature", (model.read_state(preserved)-model.read_state(whole)).abs().max(), 2e-12)
        check(f"{family}.readout_independence.probability", (preserved['probability']-whole['probability']).abs().max(), 0.)
        check(f"{family}.readout_independence.cemetery_content", (preserved['content_moment'][:, -1]-whole['content_moment'][:, -1]).abs().max(), 0.)
        check(f"{family}.readout_independence.content_bound", (preserved['content_moment'].abs()-preserved['probability'][..., None]).max(), 2e-12)

    initial = core.initial_state(1, dtype=torch.float64)
    for horizon in (.25, 1., 1.75, 4.):
        reference = ZeroDelayFlow(x=1., mu=-.25, sigma=1., reset=.8,
            spacing=core.reference.h, upper=core.reference.upper, count_cap=3)
        reference.advance_to(horizon)
        marked = reference.state[:-1].reshape(reference.layers, reference.size)
        successor = core.propagate(initial, torch.tensor(horizon, dtype=torch.float64))
        diagnosed = core.diagnose_interval(initial, horizon)
        # Tail and uniform grids have different states. Aggregate both tails to
        # a common last bin; this compares discretizations, not identical laws.
        fine = core.config['n_positions']
        actual_p, uniform_p = successor['probability'].numpy()[0], marked.sum(0)
        actual_bins = np.r_[actual_p[:fine], actual_p[fine:].sum()]
        uniform_bins = np.r_[uniform_p[:fine], uniform_p[fine:].sum()]
        check(f"marked.{horizon}.uniform_reference_aggregated_probability_l1", np.abs(actual_bins-uniform_bins).sum(), .003)
        check(f"marked.{horizon}.original_R14_count_pmf", np.max(np.abs(np.array(diagnosed["count_pmf_with_overflow"])[0]-marked.sum(1))), 2e-12)
        check(f"marked.{horizon}.original_R14_expected_count", abs(diagnosed["expected_count"][0]-reference.state[-1]), 2e-12)
        # Unbounded continuous Brownian renewal, independent of the spatial law.
        distances = 1.+.8*np.arange(256)
        z1 = (-distances+.25*horizon)/math.sqrt(horizon)
        z2 = (-distances-.25*horizon)/math.sqrt(horizon)
        tails = np.exp(np.logaddexp(log_ndtr(z1), .5*distances+log_ndtr(z2)))
        continuous_pmf = np.r_[1.-tails[0], tails[:3]-tails[1:4], tails[3]]
        check(f"continuous_initial.{horizon}.first_hit", abs(diagnosed["first_hit"][0]-float(tails[0])), .0005)
        check(f"continuous_initial.{horizon}.expected_count", abs(diagnosed["expected_count"][0]-float(tails.sum())), .002)
        check(f"continuous_initial.{horizon}.count_pmf_l1", np.abs(np.array(diagnosed["count_pmf_with_overflow"])[0]-continuous_pmf).sum(), .002)
        check(f"continuous_initial.{horizon}.upper_loss", diagnosed["upper_loss"][0], 1e-7)
        continuum.append(dict(horizon=horizon, finite_first_hit=diagnosed["first_hit"][0],
            continuous_first_hit=float(tails[0]), first_hit_absolute_error=abs(diagnosed["first_hit"][0]-float(tails[0])),
            finite_expected_count=diagnosed["expected_count"][0], continuous_expected_count=float(tails.sum()),
            expected_count_absolute_error=abs(diagnosed["expected_count"][0]-float(tails.sum())),
            finite_upper_loss=diagnosed["upper_loss"][0], continuum_acceptance_claim=False))
    diagnosis = core.diagnose_interval(initial, 4.)
    pmf = np.array(diagnosis["count_pmf_with_overflow"])[0]
    check("multiple_events_probability", pmf[2:].sum(), .1, "ge")
    check("event_count_exceeds_first_hit", diagnosis["expected_count"][0]-diagnosis["first_hit"][0], .2, "ge")
    # Deliberately wrong reset-at-interval-end candidate: remove reinjection,
    # record the lower exit separately, then reinsert only after the whole gap.
    q = core.generator.numpy()
    killed = np.zeros((size+1, size+1)); killed[:size, :size] = q
    lower_rate = float(np.asarray(core.reference.down).reshape(-1)[0])
    killed[:n, 0] -= lower_rate*core.reference.reset_law
    killed[-1, 0] = lower_rate
    wrong = expm(4.*killed)@np.r_[initial["probability"].numpy()[0], 0.]
    endpoint = wrong[:size].copy(); endpoint[:n] += wrong[-1]*core.reference.reset_law
    correct = core.propagate(initial, torch.tensor(4., dtype=torch.float64))["probability"].numpy()[0]
    check("reject_reset_only_at_interval_end", np.abs(correct-endpoint).sum(), .1, "ge")

    x = torch.randn(2, 4, 16, dtype=torch.float64)
    dt = torch.tensor([[.25, 1., 1.75, 4.], [1.75, .25, 4., 1.]], dtype=torch.float64)
    whole = core(x, dt)
    prefix = core(x[:, :2], dt[:, :2])
    changed = x.clone(); changed[:, 2:] = 1e5
    check("causal_prefix", (whole[:, :2]-prefix).abs().max().detach(), 0.)
    check("causal_future_payload", (whole[:, :2]-core(changed, dt)[:, :2]).abs().max().detach(), 0.)
    state = core.initial_state(2, dtype=torch.float64)
    online = []
    for index in range(4):
        feature, state = core.step(x[:, index], state, dt[:, index]); online.append(feature)
    check("online_prefix_alignment", (whole-torch.stack(online, 1)).abs().max().detach(), 0.)
    check("content_state_is_position_dependent", (state["content_moment"]-state["probability"][..., None]*state["content_moment"].sum(1, keepdim=True)).abs().max().detach(), 1e-4, "ge")
    target = torch.randn_like(whole)
    loss = (whole*target).sum(); loss.backward()
    for name, parameter in core.named_parameters():
        check("gradient_nonzero."+name, parameter.grad.abs().max(), 1e-9, "ge")
    selected = [("candidate.weight", (1, 2)), ("write.weight", (4, 5)),
                ("evidence.weight", (2, 3)), ("position_read", (2, 3))]
    for name, index in selected:
        parameter = dict(core.named_parameters())[name]
        analytic = float(parameter.grad[index]); original = float(parameter[index].detach())
        values = []
        for delta in (1e-5, -1e-5):
            with torch.no_grad(): parameter[index] = original+delta
            values.append(float((core(x, dt)*target).sum().detach()))
        with torch.no_grad(): parameter[index] = original
        numerical = (values[0]-values[1])/2e-5
        check("finite_difference."+name, abs(analytic-numerical), 2e-7)
    duration = torch.tensor([.63], dtype=torch.float64, requires_grad=True)
    propagated = core.propagate(initial, duration)
    weights = torch.cat((core.positions, torch.tensor([core.reference.upper], dtype=torch.float64)))[None]
    derivative = torch.autograd.grad((propagated["probability"]*weights).sum(), duration)[0]
    exact = ((core.generator@propagated["probability"][0])*weights[0]).sum()
    check("physical_time_derivative", (derivative-exact).abs().max().detach(), 2e-12)
    close = core.propagate(initial, torch.tensor(1.+2**-20, dtype=torch.float64))
    unit = core.propagate(initial, torch.tensor(1., dtype=torch.float64))
    check("time_not_rounded", (close["probability"]-unit["probability"]).abs().max(), 1e-9, "ge")
    scalar_close = core.propagate(initial, 1.+2**-30)
    check("python_scalar_time_not_downcast", (scalar_close["probability"]-unit["probability"]).abs().max(), 1e-12, "ge")
    ordinary = DistributionContentCore(family="ordinary_distribution", seed=150903).double()
    check("same_parameter_count", abs(sum(p.numel() for p in core.parameters())-sum(p.numel() for p in ordinary.parameters())), 0.)
    for (name, p), (other_name, other) in zip(core.named_parameters(), ordinary.named_parameters()):
        check("same_initial_parameter."+name, (p.detach()-other.detach()).abs().max(), 0.)
        if name != other_name: raise AssertionError("Parameter name mismatch")
    # Compare the shared-matrix fast path with the old batched expression.
    for dtype, tolerance in ((torch.float32, 2e-7), (torch.float64, 2e-12)):
        fixture = core.initial_state(8, dtype=dtype)
        fixture["content_moment"] = torch.randn_like(fixture["content_moment"])
        intervals = torch.full((8,), 1.75, dtype=torch.float64)
        matrix = core._matrices(intervals, fixture["probability"].device)
        expected_p = torch.bmm(matrix, fixture["probability"][..., None]).squeeze(-1)
        expected_m = torch.bmm(matrix.to(dtype), fixture["content_moment"])
        actual = core.propagate(fixture, intervals)
        check(f"shared_matrix.{dtype}.probability", (actual["probability"]-expected_p).abs().max(), 2e-12)
        check(f"shared_matrix.{dtype}.moment", (actual["content_moment"]-expected_m).abs().max(), tolerance)
    # Loading a changed fixed generator must invalidate a warmed transition.
    ordinary.propagate(initial, torch.tensor(1., dtype=torch.float64))
    checkpoint = {key: value.clone() for key, value in ordinary.state_dict().items()}
    checkpoint["ordinary_generator"].zero_()
    ordinary.load_state_dict(checkpoint)
    check("load_clears_transition_cache", len(ordinary._cache), 0.)
    unchanged = ordinary.propagate(initial, torch.tensor(1., dtype=torch.float64))
    check("loaded_generator_used", (unchanged["probability"]-initial["probability"]).abs().max(), 0.)
    ordinary.double()
    check("module_apply_clears_transition_cache", len(ordinary._cache), 0.)
    for invalid in (-1., float("nan"), float("inf")):
        try:
            core.propagate(initial, torch.tensor(invalid))
        except ValueError:
            rejected = True
        else:
            rejected = False
        check("reject_interval."+str(invalid), int(rejected), 1, "ge")
    return dict(schema="hcsn-r15.finite-law-checks.v1", passed=all(r["passed"] for r in records),
        checks=records, count=len(records), failed=[r for r in records if not r["passed"]],
        continuum_diagnostic=continuum, continuous_model_acceptance=False,
        trainable_parameters=sum(p.numel() for p in core.parameters()),
        state_scalars_per_row=size*(1+core.width), config=core.config,
        cpu_seconds=time.process_time()-begin,
        runtime=dict(torch=torch.__version__, numpy=np.__version__),
        scope="Finite fixed generator and explicit conditional-content-moment model only; no task confirmation data.")


def complete_successor():
    """Reproduce the independent continuous complete-successor comparison."""
    from experiments.hcsn_validation_r14_20261101.numerics.continuous_reference import successor
    edges = [0., .25, .5, 1., 2., 4., 8., np.inf]
    rows, begin = [], time.process_time()
    for horizon in (.25, 1., 1.75, 4.):
        case = dict(x=1., mu=-.25, sigma=1., reset=.8, horizon=horizon)
        reference = successor(case, edges, 3)
        from .tail_grid import TailGridFlow
        finite = TailGridFlow(x=1., mu=-.25, sigma=1., reset=.8,
            spacing=1/17, fine_positions=182, tail_spacing=.5, upper=60.,
            count_cap=3).advance_to(horizon).observables(edges)
        error = float(np.abs(np.array(finite["active_bins"])-reference["active_bins"]).sum())
        rows.append(dict(horizon=horizon, active_bins_l1_error=error, threshold=.003,
            passed=bool(error <= .003), finite=finite, continuous=reference))
    return dict(passed=all(row["passed"] for row in rows), rows=rows,
        cpu_seconds=time.process_time()-begin,
        scope="Independent continuous renewal successor at default initial atom; not arbitrary learned posterior certification")


def benchmark():
    """Fixed random tensors; model setup, cold and warm work are distinguished."""
    torch.set_num_threads(1)
    torch.manual_seed(151920)
    x = torch.randn(64, 12, 16)
    dt = torch.tensor([.25, 1., 1.75, 4.]*3)[None].expand(64, -1)
    rows = []
    for family in DistributionContentCore.FAMILIES:
        start = time.process_time()
        model = DistributionContentCore(family=family, seed=150903)
        setup = time.process_time()-start
        samples = []
        for _ in range(6):
            start = time.process_time()
            model(x, dt).square().mean().backward()
            samples.append(time.process_time()-start)
            model.zero_grad(set_to_none=True)
        rows.append(dict(family=family, config=model.config, model_setup_cpu=setup,
            parameters=sum(p.numel() for p in model.parameters()),
            cold_forward_backward_cpu=samples[0], warm_forward_backward_cpu=samples[1:],
            cache_entries=len(model._cache),
            cache_bytes=sum(matrix.numel()*matrix.element_size() for matrix in model._cache.values())))
    return dict(passed=True, rows=rows, runtime=torch.__version__,
                scope="Fixed random B64 T12 tensors; no task data, no task cost/quality acceptance")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path)
    parser.add_argument("--mode", choices=("checks", "complete-successor", "benchmark"), default="checks")
    arguments = parser.parse_args()
    result = {"checks": run, "complete-successor": complete_successor, "benchmark": benchmark}[arguments.mode]()
    if arguments.output:
        arguments.output.parent.mkdir(parents=True, exist_ok=True)
        with arguments.output.open("x") as stream:
            json.dump(result, stream, indent=2, sort_keys=True, allow_nan=False)
            stream.write("\n")
    print(json.dumps({key: value for key, value in result.items() if key not in ("checks",)}))
    raise SystemExit(0 if result["passed"] else 1)
