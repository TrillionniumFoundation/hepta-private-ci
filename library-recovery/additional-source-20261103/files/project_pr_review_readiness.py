"""Source-only, no-score admission census for frozen real-project PR questions.

Reopen the exact historical Git artifact before any counting. A source-first
candidate is a REQUEST for independent human review, never an adequate evidence
packet, certified source-family sample, or qualified Reader benchmark case.
"""

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re

from project_first_parent_diff_handoff import (
    ORIGINAL_ZIP_SHA256,
    SOURCE_COMMIT,
    SOURCE_MANIFEST_SHA256,
    assemble,
    checked_archive,
)

SCHEMA = "hepta.memorycell.real-project-review-readiness.v1"
FILE_COUNTS = {
    "byte-different-versus-first-parent": 21,
    "added-at-first-parent-step": 6,
    "unchanged-versus-first-parent": 19,
    "added-already-present-in-first-parent": 2,
    "ambiguous-multi-parent-head": 31,
    "unresolved-renamed-previous-path": 1,
}
PARTITIONS = {"train": 4, "selection": 4, "evaluation": 8}
HEX40 = re.compile(r"[0-9a-f]{40}\Z")
HEX64 = re.compile(r"[0-9a-f]{64}\Z")
# Externally fixed for this historical source cut; generated by SHA-checked
# code from the immutable 142-member GitHub Actions archive, not task labels.
CANONICAL_PACKET_SHA256 = "c56bb1f348c8a2f7ffd467f212c0d3d1db1a151ed95cac7b3c2ed0aedb25da6b"


def check(condition, why):
    if not condition:
        raise ValueError(why)


def assess(packet):
    """Fail closed on missing cases, reclassified source, or fabricated authority."""
    check(isinstance(packet, dict) and packet.get("schema") ==
          "hepta.memorycell.real-project.first-parent-review-lines.v1", "wrong original packet")
    raw = json.dumps(packet, ensure_ascii=False, sort_keys=True,
                     separators=(",", ":"), allow_nan=False).encode("utf-8")
    check(hashlib.sha256(raw).hexdigest() == CANONICAL_PACKET_SHA256,
          "source-first packet differs from immutable original ZIP replay")
    for key, expected in {
        "original_source_zip_sha256": ORIGINAL_ZIP_SHA256,
        "original_generating_commit": SOURCE_COMMIT,
        "original_source_manifest_sha256": SOURCE_MANIFEST_SHA256,
        "source_original_file_count": 80,
        "questions_count": 16,
        "project_labels_count": 4,
        "context_bytes_verified": 6503104,
        "diff_preview_file_count": 27,
        "comparison_counts": FILE_COUNTS,
        "all_review_answers_withheld": True,
        "reviewer_identity_authenticated": False,
        "independent_semantic_review": False,
        "historical_pr_discussion_authenticated": False,
        "full_pr_base_diff_certified": False,
        "complete_source_sufficiency_verified": False,
        "independent_source_family_effective_n": None,
        "actual_reader_model_calls": 0,
        "production_accepted": False,
        "parametric_memory_training_qualified": False,
        "preview_line_budget": 80,
        "preview_byte_budget": 6000,
    }.items():
        check(type(packet.get(key)) is type(expected) and packet[key] == expected,
              "original source identity, census or review authority drift: " + key)
    cases = packet.get("cases")
    check(isinstance(cases, list) and len(cases) == 16, "complete 16-task register required")
    seen_tasks, pr_files = set(), {}
    partition_counts = Counter()
    rows = []
    for q in cases:
        check(isinstance(q, dict) and set(q) == {
            "task_id", "partition", "project", "pull_number", "head_sha", "question",
            "files", "first_parent_preview_files", "unresolved_file_count",
            "source_preview_sufficient_for_answer", "human_reviewer_verdict",
            "full_pr_diff_certified", "no_model_answer_available",
        }, "question schema changed or hidden answer injected")
        key = (q["project"], q["pull_number"], q["head_sha"])
        qid = q["task_id"]
        check(isinstance(qid, str) and 10 <= len(qid) <= 256 and qid not in seen_tasks
              and isinstance(q["question"], str) and q["question"]
              and q["partition"] in PARTITIONS
              and isinstance(q["pull_number"], int) and q["pull_number"] > 0
              and HEX40.fullmatch(q["head_sha"]), "unknown or duplicate fixed task")
        check(qid.startswith(f"{q['project']}#{q['pull_number']}@{q['head_sha']}/")
              and qid.rsplit("/", 1)[-1] in ("change_intent", "verification_gap"),
              "registered task/source identity changed")
        check(q["source_preview_sufficient_for_answer"] is None
              and q["human_reviewer_verdict"] is None
              and q["full_pr_diff_certified"] is False
              and q["no_model_answer_available"] is True,
              "a source-first proposal cannot carry answer/review authority")
        seen_tasks.add(qid)
        partition_counts[q["partition"]] += 1
        docs = q["files"]
        check(isinstance(docs, list) and 1 <= len(docs) <= 32, "bounded file binding required")
        source_keys, counts, previews, truncated = [], Counter(), 0, 0
        for f in docs:
            check(isinstance(f, dict) and set(f) == {
                "source_path", "head_git_blob_sha1", "head_sha256", "parent_classification",
                "previous_git_blob_sha1", "previous_sha256", "diff",
                "complete_pr_diff_certified", "semantic_sufficiency_verified",
            }, "source row or authority drift")
            check(isinstance(f["source_path"], str)
                  and 0 < len(f["source_path"]) <= 512
                  and ".." not in Path(f["source_path"]).parts
                  and not Path(f["source_path"]).is_absolute()
                  and HEX40.fullmatch(f["head_git_blob_sha1"])
                  and HEX64.fullmatch(f["head_sha256"])
                  and f["parent_classification"] in FILE_COUNTS
                  and f["complete_pr_diff_certified"] is False
                  and f["semantic_sufficiency_verified"] is False,
                  "changed source hash/path or forged review")
            if f["previous_git_blob_sha1"] is not None:
                check(isinstance(f["previous_git_blob_sha1"], str)
                      and HEX40.fullmatch(f["previous_git_blob_sha1"]),
                      "invalid previous Git blob")
            if f["previous_sha256"] is not None:
                check(isinstance(f["previous_sha256"], str)
                      and HEX64.fullmatch(f["previous_sha256"]),
                      "invalid previous raw bytes")
            source_keys.append((f["source_path"], f["head_git_blob_sha1"],
                                f["head_sha256"], f["parent_classification"],
                                f["previous_git_blob_sha1"], f["previous_sha256"]))
            counts[f["parent_classification"]] += 1
            diff = f["diff"]
            allowed_preview = f["parent_classification"] in (
                "byte-different-versus-first-parent", "added-at-first-parent-step")
            if diff is not None:
                check(allowed_preview and isinstance(diff, dict), "invented earlier code")
                state = diff.get("state")
                check(state in ("source-exact-unified-first-parent", "unavailable-non-utf8"),
                      "unknown diff state")
                if state == "source-exact-unified-first-parent":
                    value = diff.get("text")
                    check(isinstance(value, str) and len(value.encode()) <= 6000
                          and hashlib.sha256(value.encode()).hexdigest() == diff.get("preview_sha256")
                          and type(diff.get("truncated")) is bool
                          and diff.get("preview_is_complete") is (not diff["truncated"]),
                          "byte-bounded original diff preview mutated")
                    truncated += int(diff["truncated"])
                else:
                    check(diff.get("text") is None and diff.get("preview_sha256") is None
                          and diff.get("preview_is_complete") is False,
                          "non-UTF8 source is not textual preview")
                previews += 1
            else:
                check(not allowed_preview, "missing original first-parent diff")
        check(len(source_keys) == len(set(source_keys))
              and q["first_parent_preview_files"] == previews
              and q["unresolved_file_count"] == len(docs) - previews,
              "duplicate/absent sources or false preview count")
        if key in pr_files:
            check(pr_files[key] == source_keys, "paired questions no longer share same PR sources")
        else:
            pr_files[key] = source_keys
        bucket = ("multi_parent_baseline_unresolved" if counts["ambiguous-multi-parent-head"]
                  else "renamed_prior_path_unresolved" if counts["unresolved-renamed-previous-path"]
                  else "source_first_review_candidate" if previews
                  else "no_comparable_first_parent_delta")
        rows.append(dict(task_id=qid, project=q["project"], pull_number=q["pull_number"],
                         partition=q["partition"], registered_head_sha=q["head_sha"],
                         source_first_review_bucket=bucket,
                         original_head_file_bindings=len(docs), diff_preview_file_bindings=previews,
                         unresolved_first_parent_bindings=len(docs) - previews,
                         visibly_truncated_diff_previews=truncated,
                         source_statuses=dict(counts),
                         requires_full_pr_historical_baseline=True,
                         requires_independent_human_sufficiency_review=True,
                         reader_task_eligible=False, reviewer_verdict=None))
    check(dict(partition_counts) == PARTITIONS and len(pr_files) == 8
          and set(q["project"] for q in cases) == {
              "rust-lang/rust", "kubernetes/kubernetes", "numpy/numpy", "astral-sh/ruff"
          }, "source-family partition or PR census drift")
    check(all(sum(r["source_statuses"].values()) == r["original_head_file_bindings"] for r in rows),
          "source status arithmetic drift")
    unique = Counter()
    for entries in pr_files.values():
        unique.update(x[3] for x in entries)
    check(dict(unique) == FILE_COUNTS and sum(unique.values()) == 80,
          "deduplicated original 80-file status census changed")
    buckets = Counter(r["source_first_review_bucket"] for r in rows)
    check(buckets == Counter({"source_first_review_candidate": 10,
                             "renamed_prior_path_unresolved": 2,
                             "multi_parent_baseline_unresolved": 4}),
          "frozen reviewability/ambiguity attribution changed")
    return dict(schema=SCHEMA, original_source_manifest_sha256=SOURCE_MANIFEST_SHA256,
                original_source_zip_sha256=ORIGINAL_ZIP_SHA256,
                original_generating_commit=SOURCE_COMMIT,
                fixed_questions=16, unique_pr_histories=8, source_repositories=4,
                original_file_bindings=80, source_byte_census=6503104,
                original_first_parent_diff_file_bindings=27,
                bucket_counts=dict(buckets), partition_counts=dict(partition_counts),
                actual_human_review_verdicts=0, qualified_reader_tasks=0,
                independent_source_family_effective_n=None,
                human_source_sufficiency_authenticated=False,
                historical_pr_base_diff_authenticated=False,
                parametric_learning_evidence=False,
                production_accepted=False, tasks=rows)


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("source_zip", type=Path)
    cli.add_argument("output_json", type=Path)
    args = cli.parse_args()
    report = assess(assemble(checked_archive(args.source_zip)))
    with args.output_json.open("x", encoding="utf-8") as out:
        json.dump(report, out, sort_keys=True, indent=2, allow_nan=False)
        out.write("\n")


if __name__ == "__main__":
    main()
