#[cfg(unix)]
use std::os::unix::fs::PermissionsExt;

use tempfile::TempDir;

pub(crate) fn private_tempdir(label: &str) -> TempDir {
    let temporary = tempfile::tempdir().unwrap_or_else(|error| panic!("{label}: {error}"));
    #[cfg(unix)]
    std::fs::set_permissions(temporary.path(), std::fs::Permissions::from_mode(0o700))
        .unwrap_or_else(|error| panic!("secure {label}: {error}"));
    temporary
}

pub(crate) struct SshKeyFixture {
    pub(crate) public: String,
    pub(crate) fingerprint: String,
    #[cfg(unix)]
    pub(crate) private: std::path::PathBuf,
}

#[cfg(unix)]
pub(crate) fn ssh_key_fixture(root: &std::path::Path) -> SshKeyFixture {
    use std::process::Command;

    let key = root.join("operator-key");
    let status = Command::new("/usr/bin/ssh-keygen")
        .args(["-q", "-t", "ed25519", "-N", "", "-f"])
        .arg(&key)
        .status()
        .expect("start independent OpenSSH key generation");
    assert!(status.success(), "generate test-only Ed25519 key");
    let public = std::fs::read_to_string(key.with_extension("pub")).expect("read public key");
    let output = Command::new("/usr/bin/ssh-keygen")
        .args(["-E", "sha256", "-lf"])
        .arg(key.with_extension("pub"))
        .output()
        .expect("fingerprint public key with OpenSSH");
    assert!(output.status.success());
    let fingerprint = std::str::from_utf8(&output.stdout)
        .expect("UTF-8 fingerprint output")
        .split_ascii_whitespace()
        .nth(1)
        .expect("OpenSSH fingerprint field")
        .to_string();
    SshKeyFixture {
        public,
        fingerprint,
        private: key,
    }
}

