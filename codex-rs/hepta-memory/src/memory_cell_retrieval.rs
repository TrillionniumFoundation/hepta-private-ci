/// The host authenticates this plan against its independent registry. It must
/// retain the current position outside a suspect owner database on restart.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct MemoryCellPersistencePlanV1 {
    pub manifest: MemoryCellManifestV1,
    pub retrieval_context_digest: Digest32,
    /// Actual host-owned NDU state; no substitute is generated by retrieval.
    pub ndu_state_digest: ContractDigestV1,
    pub resource_budget_units: u32,
    pub position: MemoryCellPersistencePositionV1,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub enum MemoryCellPersistencePositionV1 {
    Bootstrap,
    Resume(MemoryCellCheckpointReadPinsV1),
}

/// Only preparation can construct this exact restored context and sequence.
pub struct PreparedMemoryCellRetrievalV1 {
    plan: MemoryCellPersistencePlanV1,
    context: RetrievalExecutionContextV1,
    owner_cut_digest: ContractDigestV1,
    sequence: u64,
    predecessor: Option<ContractDigestV1>,
    restored_recall: Option<GeneratedRecallV1>,
}

#[derive(Clone, Debug)]
pub struct OwnerMemoryCellExecutionV1 {
    execution: OwnerRetrievalExecutionV1,
    /// Shadow candidate identity is distinct from the eventual owner receipt.
    tick: MemoryCellTickReceiptV1,
}

impl OwnerMemoryCellExecutionV1 {
    pub fn execution(&self) -> &OwnerRetrievalExecutionV1 {
        &self.execution
    }
    pub fn tick(&self) -> &MemoryCellTickReceiptV1 {
        &self.tick
    }
}

pub fn memory_cell_checkpoint_schema_digest_v1() -> Digest32 {
    Digest32::of_bytes(b"hepta.memory-cell.engram+generated-recall-checkpoint.v1")
}

/// Canonical source/forget identities from the actual owner scope and counters.
pub fn memory_cell_owner_frontier_digests_v1(
    cut: &DurableCognitiveSnapshot,
) -> (Digest32, Digest32) {
    let scope = cut.scope_id().as_str().as_bytes();
    let source = cut.frontiers().source.to_be_bytes();
    let forget = cut.frontiers().tombstone.to_be_bytes();
    (
        Digest32::of_parts(&[b"hepta.memory-cell.source-frontier.v1\0", scope, &source]),
        Digest32::of_parts(&[b"hepta.memory-cell.forget-frontier.v1\0", scope, &forget]),
    )
}

impl MemoryCellPersistencePlanV1 {
    pub fn validate_context(
        &self,
        context: &RetrievalExecutionContextV1,
    ) -> Result<(), MemoryCellStateErrorV1> {
        self.manifest
            .validate()
            .map_err(|error| MemoryCellStateErrorV1::Invalid(error.to_string()))?;
        context.validate()?;
        if self.retrieval_context_digest != context.binding_digest()
            || self.manifest.encoder_digest.digest()
                != context.generation_vector.encoder_preprocessor_digest
            || self.manifest.shared_base_digest.digest() != context.generation_vector.model_digest
            || self.manifest.state_schema_digest.digest()
                != memory_cell_checkpoint_schema_digest_v1()
            || self.resource_budget_units == 0
            || self.resource_budget_units > 1_000_000
        {
            return Err(MemoryCellStateErrorV1::Conflict(
                "authenticated context/model/encoder/schema or budget",
            ));
        }
        if let MemoryCellPersistencePositionV1::Resume(pins) = &self.position
            && pins.manifest != self.manifest
        {
            return Err(MemoryCellStateErrorV1::Conflict(
                "retained manifest/model/graph generation",
            ));
        }
        Ok(())
    }
}

#[allow(clippy::too_many_arguments)]
pub async fn prepare_memory_cell_retrieval_v1(
    capability: &ProductionMemoryCellStateCapability,
    access: &CognitiveAccess,
    scope: &CognitiveScope,
    cut: &DurableCognitiveSnapshot,
    context: &RetrievalExecutionContextV1,
    plan: &MemoryCellPersistencePlanV1,
    now_unix_seconds: i64,
) -> Result<PreparedMemoryCellRetrievalV1, MemoryCellStateErrorV1> {
    plan.validate_context(context)?;
    let (source, forget) = memory_cell_owner_frontier_digests_v1(cut);
    if plan.manifest.source_frontier_digest.digest() != source
        || plan.manifest.forget_frontier_digest.digest() != forget
        || context.generation_vector.scope_id != *cut.scope_id()
        || context.generation_vector.source_ledger_frontier != cut.frontiers().source
        || context.generation_vector.tombstone_frontier != cut.frontiers().tombstone
    {
        return Err(MemoryCellStateErrorV1::Conflict(
            "owner scope/source/forget frontier",
        ));
    }
    let mut restored = context.clone();
    let (sequence, predecessor, restored_recall) = match &plan.position {
        MemoryCellPersistencePositionV1::Bootstrap => (1, None, None),
        MemoryCellPersistencePositionV1::Resume(pins) => {
            let loaded = capability
                .read_current(access, scope, pins, now_unix_seconds)
                .await?;
            let graph = decode_engram_checkpoint_v1(
                loaded.state_bytes(),
                loaded.header().state_content_digest.digest(),
            )
            .map_err(|error| MemoryCellStateErrorV1::Invalid(error.to_string()))?;
            let recall = decode_recall_checkpoint_v1(
                loaded.recall_bytes(),
                loaded.header().recall_content_digest.digest(),
            )
            .map_err(|error| MemoryCellStateErrorV1::Invalid(error.to_string()))?;
            // The current authenticated context supplies the exact graph and
            // model identities; retained declarations alone cannot establish them.
            if graph != context.engram_snapshot
                || recall.packet.generation_vector_digest != context.generation_vector.digest()
                || recall.packet.policy_digest != context.retrieval_policy.digest()
                || recall.packet.packet_digest != loaded.header().recall_packet_digest.digest()
                || recall.packet.engram.as_ref().is_some_and(|receipt| {
                    receipt.engram_snapshot_digest != graph.snapshot_digest
                        || receipt.dynamics_policy_digest != context.dynamics_policy.digest()
                })
            {
                return Err(MemoryCellStateErrorV1::Conflict(
                    "restored graph/generation/RecallPacket identity",
                ));
            }
            restored.engram_snapshot = graph;
            let next = loaded
                .header()
                .logical_sequence
                .checked_add(1)
                .ok_or_else(|| {
                    MemoryCellStateErrorV1::Invalid("checkpoint sequence overflow".into())
                })?;
            (next, Some(loaded.receipt().checkpoint_digest), Some(recall))
        }
    };
    Ok(PreparedMemoryCellRetrievalV1 {
        plan: plan.clone(),
        context: restored,
        owner_cut_digest: contract(cut.cut_digest())?,
        sequence,
        predecessor,
        restored_recall,
    })
}

impl PreparedMemoryCellRetrievalV1 {
    pub fn plan(&self) -> &MemoryCellPersistencePlanV1 {
        &self.plan
    }
    pub fn restored_recall(&self) -> Option<&GeneratedRecallV1> {
        self.restored_recall.as_ref()
    }

    pub fn checkpoint_draft(
        &self,
        executed: &OwnerMemoryCellExecutionV1,
    ) -> Result<MemoryCellCheckpointDraftV1, MemoryCellStateErrorV1> {
        if executed.tick.cell_id != self.plan.manifest.cell_id
            || executed.tick.logical_sequence != self.sequence
            || executed.tick.predecessor_checkpoint_digest != self.predecessor
            || executed.tick.graph_generation != self.plan.manifest.graph_generation
            || executed.tick.model_generation != self.plan.manifest.model_generation
            || executed.tick.candidate_digest
                != Some(contract(executed.execution.recall.receipt_digest)?)
            || executed.execution.recall.packet.generation_vector_digest
                != self.context.generation_vector.digest()
        {
            return Err(MemoryCellStateErrorV1::Conflict(
                "executed tick checkpoint binding",
            ));
        }
        let state_bytes = encode_engram_checkpoint_v1(&self.context.engram_snapshot)
            .map_err(|error| MemoryCellStateErrorV1::Invalid(error.to_string()))?;
        let recall_bytes = encode_recall_checkpoint_v1(&executed.execution.recall)
            .map_err(|error| MemoryCellStateErrorV1::Invalid(error.to_string()))?;
        let draft = MemoryCellCheckpointDraftV1 {
            header: MemoryCellCheckpointHeaderV1 {
                manifest: self.plan.manifest.clone(),
                logical_sequence: self.sequence,
                predecessor_digest: self.predecessor,
                owner_cut_digest: self.owner_cut_digest,
                recall_packet_digest: contract(executed.execution.recall.packet.packet_digest)?,
                state_content_digest: contract(Digest32::of_bytes(&state_bytes))?,
                recall_content_digest: contract(Digest32::of_bytes(&recall_bytes))?,
            },
            state_bytes,
            recall_bytes,
        };
        draft.encode_header()?;
        Ok(draft)
    }
}

pub fn execute_owner_memory_cell_observation(
    observation: &RetrievalObservation,
    cut: &DurableCognitiveSnapshot,
    prepared: &PreparedMemoryCellRetrievalV1,
    request_digest: Digest32,
    acquired_at_unix_ms: u64,
    lease_expires_unix_ms: u64,
) -> Result<OwnerMemoryCellExecutionV1, MemoryCellStateErrorV1> {
    if cut.cut_digest() != prepared.owner_cut_digest.digest() {
        return Err(MemoryCellStateErrorV1::Conflict("prepared owner cut"));
    }
    let context = &prepared.context;
    let (cue, generated) = prepare_owner_observation(
        observation,
        cut,
        context,
        request_digest,
        acquired_at_unix_ms,
        lease_expires_unix_ms,
    )?;
    let manifest = &prepared.plan.manifest;
    let input = MemoryCellTickInputV1 {
        schema_version: 1,
        cell_id: manifest.cell_id.clone(),
        graph_generation: manifest.graph_generation,
        model_generation: manifest.model_generation,
        logical_sequence: prepared.sequence,
        predecessor_checkpoint_digest: prepared.predecessor,
        input_digest: contract(request_digest)?,
        cue_digest: contract(cue.digest())?,
        snapshot_digest: contract(context.engram_snapshot.snapshot_digest)?,
        source_frontier_digest: manifest.source_frontier_digest,
        forget_frontier_digest: manifest.forget_frontier_digest,
        objective_digest: contract(context.objective_digest)?,
        ndu_state_digest: prepared.plan.ndu_state_digest,
        resource_budget_units: prepared.plan.resource_budget_units,
    };
    let tick = run_memory_cell_tick(
        manifest,
        &input,
        &cue,
        &context.retrieval_policy,
        &generated,
        &context.engram_snapshot,
        &context.dynamics_policy,
    )
    .map_err(|error| MemoryCellStateErrorV1::Invalid(error.to_string()))?;
    let assignment =
        observe_retrieval_assignment(&cue, &context.retrieval_policy, &generated, &tick.recall)
            .map_err(|error| MemoryCellStateErrorV1::Invalid(error.to_string()))?;
    Ok(OwnerMemoryCellExecutionV1 {
        execution: OwnerRetrievalExecutionV1 {
            recall: tick.recall,
            assignment,
        },
        tick: tick.receipt,
    })
}

fn contract(value: Digest32) -> Result<ContractDigestV1, MemoryCellStateErrorV1> {
    ContractDigestV1::from_digest(value)
        .map_err(|error| MemoryCellStateErrorV1::Invalid(error.to_string()))
}
