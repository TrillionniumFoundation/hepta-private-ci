/// The existing authenticated launcher/provider supplies this Root0600 file.
/// Its human identity and permissions are inputs, never generated by this API.
#[derive(Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct HostAuthorityNativeProfile {
    pub schema_version: u32,
    pub program: PathBuf,
    pub program_sha256: String,
    pub arguments: Vec<String>,
    pub working_directory: PathBuf,
    pub environment: BTreeMap<String, String>,
    pub socket_path: PathBuf,
    pub principal_id: String,
    pub session_id: String,
    pub permission_revision: u64,
    pub expires_at_ms: u64,
    pub route: AgentdTextSessionConfig,
    pub can_interrupt: bool,
    #[serde(default)]
    pub can_resolve_approvals: bool,
}

#[derive(Serialize)]
pub struct NativeLaunchDiagnostic {
    pub protected_existing_inputs_verified: bool,
    pub original_daemon_lifetime_verified: bool,
    pub supplied_human_profile_within_writer_lease: bool,
    pub authority_state_opened: bool,
    pub provider_account_checked: bool,
    pub production_ready: bool,
}

fn inputs(
    config_file: &Path,
    registration_file: &Path,
    profile_file: &Path,
    owner: &OwnedFd,
) -> io::Result<(HostAuthorityServiceConfig, HostAuthorityNativeProfile)> {
    let config: HostAuthorityServiceConfig = read_root_json(config_file)?;
    let registration: HostAuthorityRegistration = read_root_json(registration_file)?;
    let profile: HostAuthorityNativeProfile = read_root_json(profile_file)?;
    if config.schema_version != 1
        || registration.schema_version != 1
        || profile.schema_version != 1
        || config.peer_uid == 0
        || config.issuer_record_profile != HostIssuerRecordProfile::TextRecovery
    {
        return Err(io::Error::other(
            "existing native Root deployment inputs are required",
        ));
    }
    config.required_bind.verify()?;
    if !config
        .state_dir
        .starts_with(&config.required_bind.mountpoint)
    {
        return Err(io::Error::other(
            "original state is outside the registered mount",
        ));
    }
    for directory in [
        config.state_dir.clone(),
        config.state_dir.join("issuer"),
        config.state_dir.join("leases"),
    ] {
        codex_hepta_contracts::RootAuthorityDirectory::open(&directory)
            .map_err(io::Error::other)?;
    }
    crate::authority_host_runtime::verify_process(&registration, config.peer_uid)?;
    let info = std::fs::read_to_string(format!("/proc/self/fdinfo/{}", owner.as_raw_fd()))?;
    if !info.lines().any(|line| {
        line.strip_prefix("Pid:")
            .is_some_and(|pid| pid.trim() == registration.peer_pid.to_string())
    }) {
        return Err(io::Error::other(
            "pre-held daemon descriptor is not the original registered pidfd",
        ));
    }
    crate::authority_host_runtime::owner_alive(
        owner,
        std::time::Instant::now() + std::time::Duration::from_secs(1),
    )?;
    let identity = registration.registered_identity.identity()?;
    let writer = config
        .writer
        .as_ref()
        .ok_or_else(|| io::Error::other("original registered writer is missing"))?;
    writer.validate()?;
    let now = crate::authbus_ingress::now_ms().map_err(io::Error::other)?;
    if profile.route.agent_id != identity.agent_id
        || profile.route.spawn_generation != identity.spawn_generation
        || profile.route.control_socket != identity.control_socket
        || profile.route.codex_home != identity.home_root
        || profile.permission_revision != writer.authority_lease.revision
        || profile.expires_at_ms <= now
        || profile.expires_at_ms > writer.authority_lease.expires_at_unix_ms
        || profile.route.thread_id.is_empty()
        || profile.route.thread_id.len() > 128
        || profile.route.app_server_session_id.is_empty()
        || profile.route.app_server_session_id.len() > 256
        || [&profile.principal_id, &profile.session_id]
            .into_iter()
            .any(|id| {
                id.is_empty()
                    || id.len() > 128
                    || !id
                        .bytes()
                        .all(|byte| byte.is_ascii_alphanumeric() || b"._:-".contains(&byte))
            })
    {
        return Err(io::Error::other(
            "supplied human/profile route differs from the existing original writer session",
        ));
    }
    if profile.program.canonicalize()? != profile.program
        || !profile.program.is_file()
        || profile.working_directory.canonicalize()? != profile.working_directory
        || !profile.working_directory.is_dir()
        || profile.arguments.len() > 32
        || profile.arguments.iter().map(String::len).sum::<usize>() > 16 * 1024
        || !profile.socket_path.is_absolute()
        || profile.socket_path.parent() != config.sockets.observation.parent()
        || [
            &config.sockets.observation,
            &config.sockets.issuer,
            &config.sockets.checkpoint,
        ]
        .into_iter()
        .chain(config.sockets.device_frontier.iter())
        .chain(config.sockets.notes_frontier.iter())
        .any(|path| path == &profile.socket_path)
        || std::fs::symlink_metadata(&profile.socket_path).is_ok()
    {
        return Err(io::Error::other(
            "invalid native program, arguments, working directory or fresh private lane",
        ));
    }
    validate_environment(&profile.environment, config.peer_uid)?;
    open_verified_program(&profile, config.peer_gid)?;
    Ok((config, profile))
}

fn validate_environment(environment: &BTreeMap<String, String>, uid: u32) -> io::Result<()> {
    let allowed = [
        "DISPLAY",
        "WAYLAND_DISPLAY",
        "XDG_RUNTIME_DIR",
        "DBUS_SESSION_BUS_ADDRESS",
        "XAUTHORITY",
        "HOME",
        "LANG",
        "LC_ALL",
        "TRILL_UI_MAKEPAD_RESOURCES",
        "XDG_STATE_HOME",
        "TRILL_UI_DRAFT_RECOVERY",
    ];
    if environment.len() > allowed.len()
        || environment.iter().any(|(key, value)| {
            !allowed.contains(&key.as_str()) || value.len() > 4096 || value.contains('\0')
        })
    {
        return Err(io::Error::other(
            "native environment must contain only bounded display/resource/draft inputs",
        ));
    }
    if environment
        .get("TRILL_UI_DRAFT_RECOVERY")
        .is_some_and(|value| value != "0" && value != "1")
    {
        return Err(io::Error::other("draft recovery must be explicitly 0 or 1"));
    }
    if !environment.contains_key("TRILL_UI_MAKEPAD_RESOURCES")
        || (environment
            .get("TRILL_UI_DRAFT_RECOVERY")
            .is_none_or(|value| value != "0")
            && !environment.contains_key("XDG_STATE_HOME"))
    {
        return Err(io::Error::other(
            "prepared original Makepad resources and explicit draft state directory are required",
        ));
    }
    for key in [
        "TRILL_UI_MAKEPAD_RESOURCES",
        "XDG_STATE_HOME",
        "HOME",
        "XDG_RUNTIME_DIR",
        "XAUTHORITY",
    ] {
        let Some(value) = environment.get(key) else {
            continue;
        };
        let path = Path::new(value);
        let metadata = std::fs::symlink_metadata(path)?;
        if !path.is_absolute()
            || path.canonicalize()? != path
            || metadata.file_type().is_symlink()
            || (key == "XAUTHORITY" && !metadata.is_file())
            || (key != "XAUTHORITY" && !metadata.is_dir())
        {
            return Err(io::Error::other(format!(
                "{key} requires an existing canonical path"
            )));
        }
        if key != "TRILL_UI_MAKEPAD_RESOURCES"
            && (metadata.uid() != uid || metadata.mode() & 0o022 != 0)
        {
            return Err(io::Error::other(format!(
                "{key} must belong to the registered UI owner and reject shared writes"
            )));
        }
    }
    Ok(())
}

fn open_verified_program(
    profile: &HostAuthorityNativeProfile,
    peer_gid: u32,
) -> io::Result<std::fs::File> {
    let mut file = std::fs::OpenOptions::new()
        .read(true)
        .custom_flags(libc::O_NOFOLLOW | libc::O_CLOEXEC)
        .open(&profile.program)?;
    let metadata = file.metadata()?;
    if !metadata.is_file()
        || metadata.uid() != 0
        || metadata.mode() & 0o022 != 0
        || !(metadata.mode() & 0o001 != 0
            || (metadata.gid() == peer_gid && metadata.mode() & 0o010 != 0))
        || metadata.len() > 2 * 1024 * 1024 * 1024
    {
        return Err(io::Error::other(
            "native program must be a bounded installed Root-owned executable",
        ));
    }
    let mut hash = Sha256::new();
    let mut buffer = [0; 64 * 1024];
    loop {
        let count = file.read(&mut buffer)?;
        if count == 0 {
            break;
        }
        hash.update(&buffer[..count]);
    }
    if format!("{:x}", hash.finalize()) != profile.program_sha256 {
        return Err(io::Error::other(
            "native program differs from the trusted profile SHA256",
        ));
    }
    Ok(file)
}

/// Read-only structural/lifetime diagnostic. Deliberately does not open the
/// issuer/clock stores or claim that supplied identity was authenticated here.
pub fn diagnose_native_launch(
    config: &Path,
    registration: &Path,
    profile: &Path,
    owner: &OwnedFd,
) -> io::Result<NativeLaunchDiagnostic> {
    inputs(config, registration, profile, owner)?;
    Ok(NativeLaunchDiagnostic {
        protected_existing_inputs_verified: true,
        original_daemon_lifetime_verified: true,
        supplied_human_profile_within_writer_lease: true,
        authority_state_opened: false,
        provider_account_checked: false,
        production_ready: false,
    })
}

struct RegistrationFile {
    path: PathBuf,
    device: u64,
    inode: u64,
}
impl Drop for RegistrationFile {
    fn drop(&mut self) {
        if std::fs::symlink_metadata(&self.path)
            .is_ok_and(|meta| meta.dev() == self.device && meta.ino() == self.inode)
        {
            let _ = std::fs::remove_file(&self.path);
        }
    }
}

/// Run from the original single-threaded Root entry. Start only the UI child;
/// the caller supplies the already running original daemon's pre-held pidfd.
pub fn launch_host_authority_native_session(
    config_file: &Path,
    registration_file: &Path,
    profile_file: &Path,
    owner: OwnedFd,
) -> io::Result<()> {
    let (config, profile) = inputs(config_file, registration_file, profile_file, &owner)?;
    let uid = config.peer_uid;
    let gid = config.peer_gid;
    let program = open_verified_program(&profile, config.peer_gid)?;
    // Execute the same verified open inode, not a path which could have been
    // replaced after hashing. The descriptor closes only after successful exec.
    let mut command = std::process::Command::new(format!("/proc/self/fd/{}", program.as_raw_fd()));
    command
        .args(&profile.arguments)
        .current_dir(&profile.working_directory)
        .env_clear()
        .envs(&profile.environment)
        .env("PATH", "/usr/bin:/bin")
        .env("TRILL_UI_CHAT_SOCKET", &profile.socket_path)
        .env("TRILL_UI_CHAT_ROOT_PID", std::process::id().to_string())
        .stdin(std::process::Stdio::null());
    // SAFETY: the original binary invokes this before creating any threads.
    // The child closure uses only async-signal-safe credential/prctl syscalls.
    unsafe {
        command.pre_exec(move || {
            if libc::setgroups(0, std::ptr::null()) != 0 {
                return Err(io::Error::last_os_error());
            }
            for cap in 0..64 {
                if libc::prctl(libc::PR_CAPBSET_DROP, cap, 0, 0, 0) != 0 {
                    let error = io::Error::last_os_error();
                    if error.raw_os_error() != Some(libc::EINVAL) {
                        return Err(error);
                    }
                }
            }
            if libc::prctl(libc::PR_SET_NO_NEW_PRIVS, 1, 0, 0, 0) != 0
                || libc::setresgid(gid, gid, gid) != 0
                || libc::setresuid(uid, uid, uid) != 0
            {
                return Err(io::Error::last_os_error());
            }
            Ok(())
        });
    }
    let mut child = command.spawn()?;
    // Retaining Child without reaping it prevents PID reuse before pidfd_open.
    // SAFETY: pidfd_open takes the actual child PID, zero flags, no pointers.
    let raw = unsafe { libc::syscall(libc::SYS_pidfd_open, child.id(), 0) };
    if raw < 0 {
        return Err(io::Error::last_os_error());
    }
    // SAFETY: successful pidfd_open returns one fresh owned descriptor.
    let ui_pidfd = unsafe { OwnedFd::from_raw_fd(raw as i32) };
    let stat = std::fs::read_to_string(format!("/proc/{}/stat", child.id()))?;
    let start = stat
        .rsplit_once(") ")
        .and_then(|(_, fields)| fields.split_whitespace().nth(19))
        .and_then(|value| value.parse().ok())
        .ok_or_else(|| io::Error::other("native UI process lifetime unavailable"))?;
    let registration = crate::HostAuthorityTextUiRegistration {
        schema_version: 1,
        socket_path: profile.socket_path,
        peer_uid: uid,
        peer_gid: gid,
        peer_pid: child.id(),
        boot_id: std::fs::read_to_string("/proc/sys/kernel/random/boot_id")?
            .trim()
            .into(),
        process_start_ticks: start,
        principal_id: profile.principal_id,
        session_id: profile.session_id,
        permission_revision: profile.permission_revision,
        expires_at_ms: profile.expires_at_ms,
        route: profile.route,
        can_interrupt: profile.can_interrupt,
        can_resolve_approvals: profile.can_resolve_approvals,
    };
    let parent = profile_file
        .parent()
        .ok_or_else(|| io::Error::other("profile has no protected parent"))?;
    let path = parent.join(format!(
        "native-ui-{}-{}.json",
        std::process::id(),
        child.id()
    ));
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .custom_flags(libc::O_NOFOLLOW | libc::O_CLOEXEC)
        .open(&path)?;
    let meta = file.metadata()?;
    let guard = RegistrationFile {
        path,
        device: meta.dev(),
        inode: meta.ino(),
    };
    serde_json::to_writer(&mut file, &registration).map_err(io::Error::other)?;
    file.flush()?;
    file.sync_all()?;
    std::fs::File::open(parent)?.sync_all()?;
    let result = crate::serve_host_authority_session_with_text(
        config_file,
        registration_file,
        owner,
        Some((&guard.path, ui_pidfd)),
    );
    // Do not kill a UI which may now contain local drafts. Its authenticated
    // owner expires/fences independently when this bounded Root session ends.
    let _ = child.try_wait();
    result
}

