//! Component assembly from one actual normal task and independently signed
//! fixture Outcome. Every E/D/Training receipt comes from its actual file owner.
//! This helper creates no Root, B, publication, or independent-custody claim.

use std::sync::Arc;
use std::sync::atomic::AtomicBool;

use codex_hepta_learning_artifacts::LearningIterationCoordinatorV1;
use codex_hepta_learning_artifacts::LearningIterationSnapshotV1;
use codex_hepta_neuron::FileAnchorWitnessStore;
use codex_hepta_types::FixedQ32;
use ed25519_dalek::SigningKey;
use pretty_assertions::assert_eq;

use super::super::fixture;
use super::super::fixture::Fixture;
use crate::CellQ24PreparedLearningV1;
use crate::CellQ24TrainingOwnerV1;
use crate::OriginalCellQ24SourceReceiptOwnerV1;
use crate::OriginalCellQ24SourceSigningConfigV1;
use crate::OriginalCellQ24SourceStageV1;
use crate::OriginalCellQ24TrainingReadbackV1;
use crate::OriginalCellQ24TrainingReceiptOwnerV1;
use crate::OriginalCellQ24TrainingSigningConfigV1;
use crate::OriginalCellQ24TrainingStageV1;

pub(super) struct TrainingFixture {
    pub(super) task: Fixture,
    pub(super) prepared: Arc<CellQ24PreparedLearningV1>,
    pub(super) dataset: LearningIterationSnapshotV1,
    pub(super) training: LearningIterationSnapshotV1,
    pub(super) stage:
        Arc<OriginalCellQ24TrainingStageV1<FileAnchorWitnessStore, FileAnchorWitnessStore>>,
    _experience: OriginalCellQ24SourceReceiptOwnerV1<FileAnchorWitnessStore>,
    _dataset_owner: OriginalCellQ24SourceReceiptOwnerV1<FileAnchorWitnessStore>,
}

impl TrainingFixture {
    pub(super) async fn complete(run: &str, business_label: FixedQ32) -> anyhow::Result<Self> {
        let task = Fixture::new(run, /*lifetime*/ 600, /*automatic*/ true).await?;
        let original_task = task.task_bytes()?;
        let mut outcome = task.outcome();
        // The fixture Observer supplies this business value; it is never taken
        // from a Cell prediction or generated by the training/evaluation owner.
        outcome.value = Some(business_label);
        let signed = task.sign_outcome(&outcome, /*lifetime*/ 300);
        task.producer
            .submit_original_terminal_outcome(outcome, &signed)?;

        let verifier = task.ledger.lock().unwrap().verifier().clone();
        let mut config = task.preparation()?;
        config.owners.evidence_trust_digest = verifier.trust_digest();
        config.owners.experience = task.signers[1].principal.principal_id.clone();
        config.owners.dataset = task.signers[1].principal.principal_id.clone();
        config.owners.trainer = task.signers[0].principal.principal_id.clone();
        config.owners.evaluator = task.signers[2].principal.principal_id.clone();
        let prepared = Arc::new(task.producer.prepare_learning(
            config,
            Vec::new(),
            task.freeze_inputs()?,
        )?);
        assert!(prepared.initial().receipts.is_empty());
        let objective = prepared.initial().request.envelope.objective_digest;
        let source_owner = |name: &str, stage| -> anyhow::Result<_> {
            Ok(OriginalCellQ24SourceReceiptOwnerV1::create(
                fixture::file(task.root.path(), name)?,
                fixture::witness(task.root.path(), &format!("{name}.witness"), objective)?,
                Arc::clone(&prepared),
                OriginalCellQ24SourceSigningConfigV1 {
                    stage,
                    signer: task.signers[1].clone(),
                    verifier: verifier.clone(),
                    maximum_signature_lifetime_seconds: 600,
                },
                SigningKey::from_bytes(&[2; 32]),
            )?)
        };
        let mut experience = source_owner(
            "comparison-experience",
            OriginalCellQ24SourceStageV1::Experience,
        )?;
        let mut dataset_owner =
            source_owner("comparison-dataset", OriginalCellQ24SourceStageV1::Dataset)?;
        experience.attest_experience()?;
        let dataset = dataset_owner
            .attest_dataset(&mut experience)?
            .snapshot()
            .clone();
        let material = prepared.training_material(dataset.clone(), prepared.scope().clone())?;
        assert_eq!(&material.batch.encoded()[..8], b"HQ24T002");
        let native = CellQ24TrainingOwnerV1::create(
            fixture::file(task.root.path(), "comparison-native")?,
            fixture::witness(task.root.path(), "comparison-native.witness", objective)?,
            material.plan,
            material.batch,
            material.rule,
        )?;
        native.require_original_dataset_provenance()?;
        let generator = OriginalCellQ24TrainingReceiptOwnerV1::create(
            fixture::file(task.root.path(), "comparison-generator")?,
            fixture::witness(task.root.path(), "comparison-generator.witness", objective)?,
            OriginalCellQ24TrainingSigningConfigV1 {
                dataset: dataset.clone(),
                scope: prepared.scope().clone(),
                signer: task.signers[0].clone(),
                verifier,
                maximum_signature_lifetime_seconds: 600,
            },
            SigningKey::from_bytes(&[1; 32]),
        )?;
        let stage = Arc::new(
            OriginalCellQ24TrainingStageV1::from_original_owners(native, generator).await?,
        );
        let completed = stage
            .execute_training(&dataset, Arc::new(AtomicBool::new(/*val*/ false)))
            .await?;
        let mut coordinator = LearningIterationCoordinatorV1::from_snapshot(dataset.clone())?;
        coordinator.record(
            completed.receipt.clone(),
            completed.receipt.observed_unix_seconds,
        )?;
        let training = coordinator.snapshot().clone();
        task.require_task_unchanged(&original_task)?;
        Ok(Self {
            task,
            prepared,
            dataset,
            training,
            stage,
            _experience: experience,
            _dataset_owner: dataset_owner,
        })
    }

    pub(super) async fn original_readback(
        &self,
    ) -> anyhow::Result<OriginalCellQ24TrainingReadbackV1> {
        Ok(OriginalCellQ24TrainingReadbackV1::from_component_owners(
            Arc::clone(&self.prepared),
            Arc::clone(&self.stage),
            self.dataset.clone(),
            self.training.clone(),
            Arc::new(AtomicBool::new(/*val*/ false)),
        )
        .await?)
    }

    pub(super) fn owner_bytes(&self) -> anyhow::Result<Vec<Vec<u8>>> {
        [
            "comparison-native",
            "comparison-native.witness",
            "comparison-generator",
            "comparison-generator.witness",
            "comparison-experience",
            "comparison-experience.witness",
            "comparison-dataset",
            "comparison-dataset.witness",
        ]
        .map(|name| std::fs::read(self.task.root.path().join(name)))
        .into_iter()
        .collect::<Result<Vec<_>, _>>()
        .map_err(Into::into)
    }
}
