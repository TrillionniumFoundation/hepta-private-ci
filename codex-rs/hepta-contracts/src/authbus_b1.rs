//! B1 topology, Basil-profile, and identity-boundary contracts.
//!
//! This module is intentionally a qualification-only boundary.  It describes
//! the small set of routes and caller evidence that an eventual Basil fork may
//! register; it does not open a socket, load a key, or grant authority.  The
//! validator is therefore conservative: an unknown route, an optional route
//! without an explicit process-bound permit, a missing registered key, or a
//! caller that only presents a service UID is rejected.

