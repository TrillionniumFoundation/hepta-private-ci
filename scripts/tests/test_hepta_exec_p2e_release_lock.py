"""Adversarial unit tests for the isolated, exact local-release lock qualification."""
from __future__ import annotations

import sys
from pathlib import Path
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from scripts.hepta_exec_p2e_release_lock import qualify_release_lock

N = 161


def fixture(n: int = N, with_external: bool = True) -> bytes:
    packages = [
        '[[package]]\nname = "codex-fixture-' + str(i)
        + '"\nversion = "0.0.0"\ndependencies = ["serde"]\n'
        for i in range(n)
    ]
    if with_external:
        packages.append(
            '[[package]]\nname = "serde"\nversion = "1.0.228"\n'
            'source = "registry+https://github.com/rust-lang/crates.io-index"\n'
            'checksum = "0123456789abcdef"\n'
        )
    return ('# This file is automatically @generated by Cargo.\n'
            'version = 4\n\n' + '\n'.join(packages)).encode()


class ReleaseLockTest(unittest.TestCase):
    def test_exact_workspace_version_only(self) -> None:
        original = fixture()
        changed, names = qualify_release_lock(original)
        self.assertEqual(len(names), N)
        self.assertEqual(changed.count(b'version = "0.162.1"'), N)
        self.assertNotIn(b'version = "0.0.0"', changed)
        self.assertEqual(
            changed.count(b'source = "registry+https://github.com/rust-lang/crates.io-index"'),
            1,
        )
        self.assertEqual(changed.count(b'checksum = "0123456789abcdef"'), 1)
        self.assertNotEqual(original, changed)

    def test_missing_workspaces_fail(self) -> None:
        with self.assertRaisesRegex(ValueError, "count"):
            qualify_release_lock(fixture(N - 1))

    def test_extra_workspace_fails(self) -> None:
        with self.assertRaisesRegex(ValueError, "count"):
            qualify_release_lock(fixture(N + 1))

    def test_duplicate_workspace_id_fails(self) -> None:
        original = fixture().replace(b'codex-fixture-160', b'codex-fixture-0')
        with self.assertRaisesRegex(ValueError, "duplicate"):
            qualify_release_lock(original)

    def test_external_dependency_must_not_be_rewritten(self) -> None:
        original = fixture().replace(
            b'name = "serde"\nversion = "1.0.228"',
            b'name = "serde"\nversion = "0.0.0"',
        )
        with self.assertRaisesRegex(ValueError, "count"):
            qualify_release_lock(original)

    def test_zero_version_with_external_source_fails(self) -> None:
        original = fixture().replace(
            b'name = "codex-fixture-0"\nversion = "0.0.0"',
            b'name = "codex-fixture-0"\nversion = "0.0.0"\nsource = "registry+bad"',
        )
        with self.assertRaisesRegex(ValueError, "external"):
            qualify_release_lock(original)

    def test_already_released_member_fails(self) -> None:
        original = fixture().replace(
            b'name = "codex-fixture-0"\nversion = "0.0.0"',
            b'name = "codex-fixture-0"\nversion = "0.162.1"',
        )
        with self.assertRaisesRegex(ValueError, "count"):
            qualify_release_lock(original)

    def test_invalid_header_fails(self) -> None:
        with self.assertRaisesRegex(ValueError, "unexpected"):
            qualify_release_lock(b'version = 4\n')

    def test_layout_ambiguity_fails(self) -> None:
        original = fixture().replace(
            b'name = "codex-fixture-0"\nversion = "0.0.0"',
            b'name = "codex-fixture-0"\nversion =  "0.0.0"',
        )
        with self.assertRaisesRegex(ValueError, "layout"):
            qualify_release_lock(original)

    def test_oversize_fails(self) -> None:
        with self.assertRaisesRegex(ValueError, "oversized"):
            qualify_release_lock(fixture() + b'#' * (1024 * 1024))


if __name__ == "__main__":
    unittest.main()
