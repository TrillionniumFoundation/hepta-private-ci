#!/usr/bin/env python3
"""Produce hosted dependency-lock proposals without qualifying a changed tree.

Only the explicit GitHub Actions workflow may execute the fixed Cargo/Bazel
commands. Local controls exercise parsing, mutation scope and interrupted-record
handling without running either tool. Generated bytes remain proposals until a
reviewed successor commits the manifest and both lockfiles together.
"""

import argparse
import datetime
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time
import tomllib


ROOT = Path(__file__).resolve().parents[1]
INPUTS = ("codex-rs/Cargo.toml", "codex-rs/Cargo.lock", "MODULE.bazel.lock")
TARGETS = {
    "ctutils": (
        "0.4.6",
        "fe3e9d21d39e6f39ff46e03d5b621424f88ee23d8a1672c6bfc9ccc7f2da4f6a",
    ),
    "zstd": (
        "0.14.3",
        "db3ae9bf90af6e40197bef767eeefc46ad6397420fe873830bd85e5fbbfb3c70",
    ),
    "zstd-safe": (
        "8.2.0",
        "ded520f16b29e1a9b771c722221b2b0a0398c2316d9bb3c42b458a5414d7434b",
    ),
}
COMMANDS = (
    ("cargo-version", ".", ["cargo", "+1.96.0", "--version", "--verbose"]),
    ("bazel-version", ".", ["bazel", "--version"]),
    ("just-version", ".", ["just", "--version"]),
    (
        "cargo-update",
        "codex-rs",
        ["cargo", "+1.96.0", "update", "--package", "ctutils", "--precise", "0.4.6"],
    ),
    (
        "cargo-metadata",
        "codex-rs",
        [
            "cargo",
            "+1.96.0",
            "metadata",
            "--locked",
            "--all-features",
            "--format-version",
            "1",
        ],
    ),
    ("bazel-lock-update", ".", ["just", "bazel-lock-update"]),
    ("bazel-lock-check", ".", ["just", "bazel-lock-check"]),
)


def now():
    return datetime.datetime.now(datetime.timezone.utc).isoformat()


def sha256(raw):
    return hashlib.sha256(raw).hexdigest()


def write_json(path, value):
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2) + "\n", encoding="utf-8")
    temporary.replace(path)


def git(*args):
    return subprocess.check_output(["git", *args], cwd=ROOT).decode().strip()


def source_from_event(environment, event):
    repository = "TrillionniumFoundation/hepta-private-ci"
    if environment.get("GITHUB_REPOSITORY") != repository:
        raise ValueError("unexpected proposal repository")
    kind = environment.get("GITHUB_EVENT_NAME")
    if kind == "workflow_dispatch":
        if "pull_request" in event:
            raise ValueError("dispatch cannot contain a PR source")
        source = event.get("inputs", {}).get("source_sha")
        if source != environment.get("GITHUB_SHA"):
            raise ValueError("dispatch source must equal the workflow run SHA")
    elif kind == "pull_request":
        if event.get("inputs") or event.get("action") not in {
            "opened",
            "synchronize",
            "reopened",
        }:
            raise ValueError("PR source cannot use dispatch inputs or another action")
        pr = event.get("pull_request", {})
        head = pr.get("head", {})
        head_repo = head.get("repo", {})
        if (
            head_repo.get("full_name") != repository
            or head_repo.get("fork") is not False
        ):
            raise ValueError("proposal rejects fork and foreign-repository PR sources")
        if pr.get("base", {}).get("repo", {}).get("full_name") != repository:
            raise ValueError("proposal PR base repository mismatch")
        number = event.get("number")
        if (
            type(number) is not int
            or number <= 0
            or environment.get("GITHUB_REF") != f"refs/pull/{number}/merge"
        ):
            raise ValueError("proposal PR event/ref mismatch")
        source = head.get("sha")
    else:
        raise ValueError(
            "proposal requires workflow_dispatch or a restricted pull_request event"
        )
    if not isinstance(source, str) or not re.fullmatch(r"[0-9a-f]{40}", source):
        raise ValueError("source must be one complete lowercase commit SHA")
    return source


def require_hosted(source, output):
    if os.environ.get("GITHUB_ACTIONS") != "true":
        raise ValueError(
            "proposal execution is restricted to the declared hosted workflow"
        )
    event = json.loads(Path(os.environ["GITHUB_EVENT_PATH"]).read_text())
    if (
        source_from_event(os.environ, event) != source
        or git("rev-parse", "HEAD") != source
    ):
        raise ValueError(
            "event source and actual checkout must equal the declared source"
        )
    runner_temp = Path(os.environ["RUNNER_TEMP"]).resolve(strict=True)
    if not output.is_relative_to(runner_temp) or output.is_relative_to(ROOT):
        raise ValueError(
            "proposal output must be outside the checkout under RUNNER_TEMP"
        )


def change_manifest(raw):
    document = tomllib.loads(raw.decode())
    if document["workspace"]["dependencies"].get("zstd") != "0.13":
        raise ValueError("expected the original workspace zstd constraint")
    old = b'\nzstd = "0.13"\n'
    if raw.count(old) != 1:
        raise ValueError("zstd declaration is not the one reviewed exact line")
    changed = raw.replace(old, b'\nzstd = "0.14.3"\n')
    expected = document
    expected["workspace"]["dependencies"]["zstd"] = "0.14.3"
    if tomllib.loads(changed.decode()) != expected:
        raise ValueError("manifest mutation changed unrelated semantics")
    return changed


def check_lock(raw):
    packages = tomllib.loads(raw.decode())["package"]
    observed = {}
    for name, (version, checksum) in TARGETS.items():
        selected = [package for package in packages if package["name"] == name]
        if len(selected) != 1:
            raise ValueError(
                f"expected exactly one resolved {name}, found {len(selected)}"
            )
        package = selected[0]
        if (
            package["version"] != version
            or package.get("checksum") != checksum
            or package.get("source")
            != "registry+https://github.com/rust-lang/crates.io-index"
        ):
            raise ValueError(
                f"resolved {name} does not match the reviewed registry record"
            )
        observed[name] = {
            key: package[key] for key in ("version", "source", "checksum")
        }
    bigint = [
        package["version"] for package in packages if package["name"] == "crypto-bigint"
    ]
    return {
        "selected": observed,
        "crypto_bigint_versions": bigint,
        "crypto_bigint_blocker_closed": False,
    }


def validate_changed_paths(paths):
    unexpected = sorted(set(paths) - set(INPUTS))
    if unexpected:
        raise ValueError(
            "proposal changed unapproved tracked paths: " + ", ".join(unexpected)
        )


def save_record(output, record):
    write_json(output / "record.json", record)


def prepare(output, source):
    require_hosted(source, output)
    if output.exists():
        raise ValueError("refusing to overwrite or combine a previous proposal")
    if git("status", "--porcelain", "--untracked-files=normal"):
        raise ValueError("proposal source checkout must start clean")
    output.mkdir(parents=True)
    (output / "original").mkdir()
    (output / "logs").mkdir()
    record = {
        "schema": "hepta-pon-dependency-proposal-v1",
        "source": source,
        "source_tree": git("rev-parse", "HEAD^{tree}"),
        "started_at_utc": now(),
        "run_id": os.environ.get("GITHUB_RUN_ID"),
        "run_attempt": os.environ.get("GITHUB_RUN_ATTEMPT"),
        "github_event_name": os.environ.get("GITHUB_EVENT_NAME"),
        "github_run_sha": os.environ.get("GITHUB_SHA"),
        "github_ref": os.environ.get("GITHUB_REF"),
        "proposal_only": True,
        "native_builds_or_tests_requested": False,
        "committed_source_qualified": False,
        "all_advisories_closed": False,
        "workflow_step_timeout_minutes": 35,
        "workflow_job_timeout_minutes": 75,
        "timeout_policy": "GitHub step timeout; no PID killing; interrupted exit and settlement remain unknown",
        "original": {},
        "stages": [
            {
                "name": name,
                "cwd": cwd,
                "command": command,
                "state": "not_started",
                "exit_code": None,
            }
            for name, cwd, command in COMMANDS
        ],
        "state": "preparing",
    }
    save_record(output, record)
    for path in INPUTS:
        full = ROOT / path
        if full.is_symlink() or not full.is_file():
            raise ValueError("proposal input must be a regular tracked file")
        raw = full.read_bytes()
        target = output / "original" / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(raw)
        record["original"][path] = {"bytes": len(raw), "sha256": sha256(raw)}
        save_record(output, record)
    # Fail before modifying the candidate if this is not the reviewed dependency generation.
    change_manifest((ROOT / INPUTS[0]).read_bytes())
    versions = {
        (p["name"], p["version"])
        for p in tomllib.loads((ROOT / INPUTS[1]).read_text())["package"]
    }
    if not {
        ("ctutils", "0.4.2"),
        ("zstd", "0.13.3"),
        ("zstd-safe", "7.2.4"),
        ("crypto-bigint", "0.5.5"),
    }.issubset(versions):
        raise ValueError(
            "source dependency generation differs from the reviewed original"
        )
    record["state"] = "prepared"
    save_record(output, record)


def run(output, source):
    require_hosted(source, output)
    record = json.loads((output / "record.json").read_text())
    if record["source"] != source or record["state"] != "prepared":
        raise ValueError("proposal is not an untouched prepared source")
    if git("status", "--porcelain", "--untracked-files=normal"):
        raise ValueError("source changed after proposal preparation")
    for path, identity in record["original"].items():
        if sha256((ROOT / path).read_bytes()) != identity["sha256"]:
            raise ValueError("prepared input bytes changed")
    manifest = ROOT / INPUTS[0]
    manifest.write_bytes(change_manifest(manifest.read_bytes()))
    record["state"] = "running"
    record["declared_manifest_mutation"] = {
        "path": INPUTS[0],
        "zstd_before": "0.13",
        "zstd_after": "0.14.3",
    }
    save_record(output, record)
    for stage in record["stages"]:
        stage.update(state="running", started_at_utc=now())
        save_record(output, record)
        started = time.monotonic()
        with (
            (output / "logs" / (stage["name"] + ".stdout.txt")).open("wb") as stdout,
            (output / "logs" / (stage["name"] + ".stderr.txt")).open("wb") as stderr,
        ):
            try:
                code = subprocess.run(
                    stage["command"],
                    cwd=ROOT / stage["cwd"],
                    stdout=stdout,
                    stderr=stderr,
                    check=False,
                ).returncode
            except OSError as error:
                stage.update(
                    state="launch_failed",
                    launch_error=str(error),
                    exit_code=None,
                    wall_seconds=time.monotonic() - started,
                    finished_at_utc=now(),
                )
                record["state"] = "failed"
                save_record(output, record)
                return 1
        stage.update(
            state="succeeded" if code == 0 else "failed",
            exit_code=code,
            wall_seconds=time.monotonic() - started,
            finished_at_utc=now(),
        )
        if code != 0:
            record["state"] = "failed"
            save_record(output, record)
            return code if code > 0 else 1
        save_record(output, record)
    record["state"] = "generated"
    save_record(output, record)
    return 0


def interrupted_stages(stages):
    return [stage["name"] for stage in stages if stage["state"] == "running"]


def finalize(output, source):
    require_hosted(source, output)
    record = json.loads((output / "record.json").read_text())
    if record["source"] != source:
        raise ValueError("finalizer source mismatch")
    record["interrupted_or_unknown_stages"] = interrupted_stages(record["stages"])
    record["workflow_proposal_step_outcome"] = os.environ.get(
        "PROPOSAL_STEP_OUTCOME", "unknown"
    )
    record["finalized_at_utc"] = now()
    paths = [path for path in git("diff", "--name-only").splitlines() if path]
    record["changed_tracked_paths"] = paths
    errors = []
    if record["state"] == "preparing":
        errors.append(
            "source preparation did not finish; partial original receipts retained"
        )
    try:
        validate_changed_paths(paths)
        if git("diff", "--cached", "--name-only"):
            raise ValueError("proposal unexpectedly staged files")
        if git("ls-files", "--others", "--exclude-standard"):
            raise ValueError("proposal unexpectedly created untracked checkout files")
        for path, identity in record["original"].items():
            if sha256((output / "original" / path).read_bytes()) != identity["sha256"]:
                raise ValueError("retained original input changed")
        expected_manifest = change_manifest(
            (output / "original" / INPUTS[0]).read_bytes()
        )
        if (ROOT / INPUTS[0]).read_bytes() != expected_manifest:
            raise ValueError(
                "final manifest contains bytes outside the declared mutation"
            )
        record["resolved_graph_review"] = check_lock((ROOT / INPUTS[1]).read_bytes())
    except (ValueError, KeyError, OSError) as error:
        errors.append(str(error))
    record["review_errors"] = errors
    for path in INPUTS:
        target = output / "proposal" / path
        target.parent.mkdir(parents=True, exist_ok=True)
        try:
            if (ROOT / path).is_symlink():
                raise ValueError("refusing to retain a symlink proposal input: " + path)
            shutil.copyfile(ROOT / path, target)
        except (OSError, ValueError) as error:
            errors.append(str(error))
    patch = subprocess.check_output(
        ["git", "diff", "--binary", "--", *INPUTS], cwd=ROOT
    )
    (output / "proposal.patch").write_bytes(patch)
    record["ready_for_review"] = (
        record["state"] == "generated"
        and not errors
        and not record["interrupted_or_unknown_stages"]
    )
    save_record(output, record)
    entries = []
    for path in sorted(output.rglob("*")):
        if path.is_file() and path.name != "files.json":
            raw = path.read_bytes()
            entries.append(
                {
                    "path": path.relative_to(output).as_posix(),
                    "bytes": len(raw),
                    "sha256": sha256(raw),
                }
            )
    write_json(
        output / "files.json",
        {"schema": "hepta-proposal-file-manifest-v1", "files": entries},
    )
    print(
        json.dumps(
            {
                "state": record["state"],
                "ready_for_review": record["ready_for_review"],
                "committed_source_qualified": False,
                "all_advisories_closed": False,
                "review_errors": errors,
            }
        )
    )
    return 0 if record["ready_for_review"] else 1


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("prepare", "run", "finalize"))
    parser.add_argument("--source", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        output = args.output.resolve()
        if args.mode == "prepare":
            prepare(output, args.source)
            return 0
        if args.mode == "run":
            return run(output, args.source)
        return finalize(output, args.source)
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as error:
        print("dependency proposal rejected: " + str(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
