"""Immutable local Cell weights and a fitted two-slot router for blind inference.

A graph either relays the first model's generated bytes in a tool turn or gives
both models the original input. The second generation always supplies the final
answer. No verifier, reference answer or teacher is available to prediction.
"""

from contextlib import ExitStack
from dataclasses import asdict
import hashlib
import math
from pathlib import Path
import time

from .. import adoption, chat_protocol, coding_sft, data
from . import circuit_contract, circuit_router
from .circuit_contract import (
    Budget,
    CellSpec,
    Graph,
    digest,
    is_sha,
    measured_output,
    require,
    validate,
)

SCHEMA = "hepta.frozen-circuit-bundle.v1"
FAMILY = "hepta-local-routed-circuit-v1"
PROFILE = "local_last_answer_v1"


def execution_binding():
    paths = [
        __file__,
        circuit_contract.__file__,
        circuit_router.__file__,
        coding_sft.__file__,
        chat_protocol.__file__,
        data.__file__,
    ]
    return digest({Path(path).name: coding_sft.file_hash(path) for path in paths})


def input_manifest(bundle):
    return bundle["models"][min(bundle["models"])]


def _settings(model):
    return {
        k: v
        for k, v in model["runtime"].items()
        if k not in ("base_directory", "adapter_directory")
    }


def _registry(models, budget):
    require(
        isinstance(models, dict) and 2 <= len(models) <= 16,
        "two to sixteen local Cell models required",
    )
    group = digest({key: digest(model) for key, model in models.items()})
    cells = {}
    for key, model in models.items():
        require(
            model["schema"] == coding_sft.MODEL_SCHEMA
            and model["family"] == coding_sft.FAMILY,
            "unsupported local Cell model",
        )
        settings = _settings(model)
        require(
            chat_protocol.protocol_name(settings) == chat_protocol.NATIVE
            and is_sha(settings.get("chat_template_sha256")),
            "bound native chat required",
        )
        for name, cap in (
            ("max_input_tokens", budget.max_input_tokens_per_call),
            ("max_new_tokens", budget.max_output_tokens_per_call),
        ):
            require(
                type(settings.get(name)) is int and 0 < settings[name] <= cap,
                "Cell token cap exceeds circuit budget",
            )
        base = Path(model["runtime"]["base_directory"])
        base_files = {
            str(Path(row["path"]).relative_to(base)): row["sha256"]
            for row in model["files"]
            if Path(row["path"]).is_relative_to(base)
        }
        require("model.safetensors" in base_files, "base tensor inventory missing")
        cells[key] = CellSpec(
            key, digest(model), digest(base_files), group, digest(settings)
        )
    return cells


def _graph(row):
    return Graph(row["graph_id"], tuple(row["path"]), tuple(row["edges"]))


def _check_graph(cells, graph, budget):
    validate(cells, graph, budget)
    require(
        graph.path[0] != graph.path[1] and graph.edges in ((), ("answer",)),
        "local profile requires distinct Cells with at most an answer edge",
    )


def _components(bundle):
    require(
        bundle.get("schema") == SCHEMA
        and bundle.get("family") == FAMILY
        and (bundle.get("parent") is None or is_sha(bundle["parent"])),
        "invalid frozen circuit identity",
    )
    budget = Budget(**bundle["budget"])
    cells = _registry(bundle["models"], budget)
    require(
        bundle["runtime"] == _settings(input_manifest(bundle)),
        "circuit inference settings changed",
    )
    router = circuit_router.FrozenRouter(bundle["router"], bundle["router_sha256"])
    record = router.record
    require(
        record.get("training_only") == "A"
        and record.get("frozen") is True
        and is_sha(record.get("training_plan_digest"))
        and record.get("training_record_digests")
        and all(is_sha(d) for d in record["training_record_digests"]),
        "fitted router training bindings required",
    )
    require(
        record["plan"]["execution_binding_digest"] == execution_binding()
        and record["cell_registry_digest"]
        == digest({key: asdict(cell) for key, cell in cells.items()})
        and record["budget_digest"] == digest(asdict(budget)),
        "router execution or registry binding differs",
    )
    bindings = bundle.get("router_training_inputs")
    require(
        isinstance(bindings, list)
        and len(bindings) == len(record["training_record_digests"]),
        "router training input coverage differs",
    )
    for original, row in zip(record["training_record_digests"], bindings, strict=True):
        require(
            isinstance(row, dict)
            and set(row) == {"record_sha256", "input_ids_sha256"}
            and row["record_sha256"] == original
            and is_sha(row["input_ids_sha256"]),
            "router training token binding differs",
        )
    covered = set()
    for entry in record["graphs"]:
        graph = _graph(entry)
        _check_graph(cells, graph, budget)
        covered.update(graph.path)
    require(covered == set(cells), "unrouted Cell in bundle")
    return router, cells, budget


def checked_bundle(bundle, materials):
    _components(bundle)
    for model in bundle["models"].values():
        coding_sft.verify_model(model, materials)
    return digest(bundle)


def _task(value):
    task = value.get("task", value)
    return {
        "input": task["input"],
        "messages": chat_protocol.inference_messages(
            task["input"], task.get("messages")
        ),
    }


def _request(task, graph, slot, nodes, budget):
    visible = {"input": task["input"], "messages": list(task["messages"])}
    if slot and graph.edges:
        answer = nodes[0]["output"]["answer"]
        require(
            len(answer.encode("utf-8")) <= budget.max_relay_bytes,
            "answer exceeds frozen relay bound",
        )
        visible["messages"].append({"role": "tool", "content": answer})
    return visible


def _cost(nodes):
    return {
        "model_calls": len(nodes),
        "input_tokens": sum(n["output"]["input_tokens"] for n in nodes),
        "output_tokens": sum(n["output"]["output_tokens"] for n in nodes),
        "provider_seconds": sum(n["output"]["elapsed_seconds"] for n in nodes),
        "verifier_calls": 0,
    }


class LocalCells:
    def __init__(self, models, materials):
        self.stack = ExitStack()
        self.predictors = {}
        try:
            for key, model in models.items():
                predictor = coding_sft.load_predictor(model, materials)
                self.stack.callback(predictor.close)
                self.predictors[key] = predictor
        except BaseException:
            self.stack.close()
            raise

    def close(self):
        self.stack.close()

    def generate(self, cell, task):
        return self.predictors[cell].predict({"task": task}, retain_encoding=True)


def execute(task, graph, cells, budget, generate):
    """Produce the same blind final-slot answer for router fitting and inference."""
    _check_graph(cells, graph, budget)
    original = _task(task)
    nodes = []
    for slot, key in enumerate(graph.path):
        request = _request(original, graph, slot, nodes, budget)
        output = generate(key, request)
        measured_output(output, cells[key], budget)
        nodes.append(
            {"slot": slot, "cell_id": key, "request": request, "output": output}
        )
    return nodes


def training_graph(record, graph, cells, budget, generate, verify, directory):
    directory.mkdir(parents=True, exist_ok=False)
    nodes = execute(record, graph, cells, budget, generate)
    outcome = verify(record, nodes[-1]["output"]["answer"])
    result = {
        "nodes": nodes,
        "success": outcome["success"],
        "outcome": outcome,
        "cost": {**_cost(nodes), "verifier_calls": 1},
    }
    coding_sft.write_new(directory / "RESULT.json", result)
    return result


def fit_bundle(records, models, graphs, budget, materials, out, *, parent=None):
    """Fit with actual local generations and retain every graph-search observation."""
    from contextlib import closing

    cells = _registry(models, budget)
    for graph in graphs:
        _check_graph(cells, graph, budget)
    for record in records:
        data.validate_record(record, require_outcome=False)
    with closing(LocalCells(models, materials)) as backend:
        router, search = circuit_router.fit_router(
            records,
            graphs,
            cells,
            budget,
            backend.generate,
            data.verify_answer,
            out,
            plan=circuit_router.RouterPlan(execution_binding()),
            execution_profile=PROFILE,
        )
    training_inputs = []
    for index, record in enumerate(records):
        # The same original task enters slot zero of every topology. Retain the
        # actual token IDs from a measured generation, before any relay or scoring.
        observed = search["observations"][index * len(graphs)]
        result = adoption.read_json(Path(out) / observed["result_path"])
        require(
            observed["task_id"] == record["task_id"]
            and digest(result) == observed["result_digest"],
            "router training source or generated evidence changed",
        )
        training_inputs.append(
            {
                "record_sha256": digest(record),
                "input_ids_sha256": result["nodes"][0]["output"]["input_ids_sha256"],
            }
        )
    bundle = {
        "schema": SCHEMA,
        "router_training_inputs": training_inputs,
        "family": FAMILY,
        "parent": parent,
        "budget": asdict(budget),
        "models": models,
        "runtime": _settings(models[min(models)]),
        "router": router.record,
        "router_sha256": router.expected_digest,
    }
    checked_bundle(bundle, materials)
    coding_sft.write_new(Path(out) / "BUNDLE.json", bundle)
    return bundle


def _prediction(model_digest, routed, graph, nodes, elapsed):
    first, last = nodes[0]["output"], nodes[-1]["output"]
    return {
        **last,
        **{
            key: first[key]
            for key in (
                "input_sha256",
                "rendered_input_sha256",
                "input_tokens",
                "input_ids",
                "input_ids_sha256",
                "rendered_input",
            )
        },
        "loaded_model_digest": model_digest,
        "elapsed_seconds": elapsed,
        "time_scope": "route and both local generations; excludes model load",
        "circuit_trace": {
            "profile": PROFILE,
            "route": routed,
            "graph": asdict(graph),
            "nodes": nodes,
            "cost": _cost(nodes),
        },
    }


class Predictor:
    def __init__(self, bundle, materials):
        self.router, self.cells, self.budget = _components(bundle)
        self.model_digest = digest(bundle)
        self.backend = LocalCells(bundle["models"], materials)

    def close(self):
        self.backend.close()

    def predict(self, record):
        started = time.perf_counter()
        task = _task(record)
        graph, routed = self.router.route({"record_id": "visible", "task": task})
        nodes = execute(task, graph, self.cells, self.budget, self.backend.generate)
        return _prediction(
            self.model_digest, routed, graph, nodes, time.perf_counter() - started
        )


def load_predictor(bundle, materials):
    return Predictor(bundle, materials)


def check_prediction(bundle, raw_prediction, visible_task, tokenizer=None):
    """Replay the route, relay and retained measurements without additional model calls."""
    router, cells, budget = _components(bundle)
    task = _task(visible_task)
    graph, route = router.route({"record_id": "visible", "task": task})
    raw = raw_prediction
    trace = raw["circuit_trace"]
    require(
        trace["profile"] == PROFILE and digest(trace["graph"]) == digest(asdict(graph)),
        "retained graph differs",
    )
    for key in ("router_digest", "graph_id", "scores", "features_digest", "reads"):
        require(trace["route"][key] == route[key], "retained routing decision differs")
    for key in (
        "prompt_bytes",
        "lexical_hashes",
        "score_dot_mac",
        "full_operation_count_known",
    ):
        require(
            trace["route"]["cost"][key] == route["cost"][key],
            "retained router cost differs",
        )
    for key in ("wall_seconds", "cpu_seconds"):
        value = trace["route"]["cost"][key]
        require(
            type(value) in (int, float) and math.isfinite(value) and value >= 0,
            "invalid router timing",
        )
    nodes = trace["nodes"]
    require(len(nodes) == len(graph.path), "missing circuit node")
    for slot, key in enumerate(graph.path):
        node = nodes[slot]
        expected = _request(task, graph, slot, nodes, budget)
        require(
            node["slot"] == slot
            and node["cell_id"] == key
            and node["request"] == expected,
            "retained node or answer relay differs",
        )
        output = node["output"]
        measured_output(output, cells[key], budget)
        require(
            output["message_protocol"] == chat_protocol.NATIVE
            and is_sha(output["rendered_input_sha256"])
            and hashlib.sha256(output["rendered_input"].encode()).hexdigest()
            == output["rendered_input_sha256"]
            and digest(output["input_ids"]) == output["input_ids_sha256"]
            and len(output["input_ids"]) == output["input_tokens"]
            and len(output["output_ids"]) == output["output_tokens"]
            and all(
                type(token) is int and token >= 0
                for token in output["input_ids"] + output["output_ids"]
            )
            and output["max_new_tokens"]
            == bundle["models"][key]["runtime"]["max_new_tokens"],
            "retained encoded generation differs",
        )
        termination = chat_protocol.generation_termination(
            output["output_ids"], output["eos_token_id"], output["max_new_tokens"]
        )
        require(
            all(output[k] == v for k, v in termination.items()),
            "retained generation termination differs",
        )
        if tokenizer is not None:
            text = coding_sft.prompt_text(
                expected["input"], tokenizer, chat_protocol.NATIVE, expected["messages"]
            )
            require(
                text == output["rendered_input"]
                and tokenizer.encode(text, add_special_tokens=False)
                == output["input_ids"]
                and tokenizer.eos_token_id == output["eos_token_id"]
                and tokenizer.decode(output["output_ids"], skip_special_tokens=True)
                == output["answer"],
                "retained encoding differs from bound tokenizer",
            )
        require(
            output["input_sha256"] == hashlib.sha256(task["input"].encode()).hexdigest()
            and output["pid"] == raw["pid"]
            and output["external_effect_executed"] is False,
            "raw Cell generation identity differs",
        )
    require(
        type(raw["elapsed_seconds"]) in (int, float)
        and math.isfinite(raw["elapsed_seconds"])
        and raw["elapsed_seconds"] >= _cost(nodes)["provider_seconds"],
        "invalid circuit elapsed time",
    )
    expected = _prediction(
        digest(bundle), trace["route"], graph, nodes, raw["elapsed_seconds"]
    )
    require(digest(expected) == digest(raw), "retained costs or final answer differ")
