#!/usr/bin/env python3
"""Generate and verify the authoritative learning.eval current-status document."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATE_PATH = ROOT / "docs/modules/learning.eval/CURRENT_STATE.json"
STATUS_PATH = ROOT / "docs/modules/learning.eval/CURRENT_STATUS.md"
MAP_PATH = ROOT / "docs/modules/learning.eval/IMPLEMENTATION_MAP.json"
LIB_PATH = ROOT / "codex-rs/hepta-intelligence-eval/src/lib.rs"
EVAL_ROOT = ROOT / "codex-rs/hepta-intelligence-eval"
RAW_PRIMITIVES = (
    "decide_with_signed_evidence_v2",
    "decide_with_signed_longitudinal_evidence_v3",
)


def fail(message: str) -> None:
    raise SystemExit(f"learning.eval status: {message}")


def load_json(path: Path) -> dict:
    if not path.is_file():
        fail(f"missing {path.relative_to(ROOT)}")
    return json.loads(path.read_text(encoding="utf-8"))


def status_label(value: object) -> str:
    if value is True:
        return "implemented"
    if value is False:
        return "open"
    return str(value)


def render(state: dict) -> str:
    source = state["sourceState"]
    qualification = state["qualification"]
    external = state["externalEvidenceGates"]
    lines = [
        "# learning.eval current status",
        "",
        "> Generated from `CURRENT_STATE.json` by `scripts/hepta-learning-eval-status.py`. Do not edit this file directly.",
        "",
        f"- **Module:** `{state['module']}`",
        f"- **Owner / deputy:** `{state['owner']}` / `{state['deputy']}`",
        f"- **Authority ceiling:** `{state['authority']}`",
        "",
        "## Repository-controlled source state",
        "",
        "| State | Truth |",
        "|---|---|",
    ]
    for key, value in source.items():
        lines.append(f"| `{key}` | **{status_label(value)}** |")
    lines.extend(
        [
            "",
            "## Registered repository consumers",
            "",
            "| Consumer | Source | Admitted surface | Authority |",
            "|---|---|---|---|",
        ]
    )
    for consumer in state["repositoryConsumers"]:
        lines.append(
            f"| `{consumer['id']}` | `{consumer['path']}` | `{consumer['surface']}` | `{consumer['authority']}` |"
        )
    lines.extend(
        [
            "",
            "## Dynamic qualification evidence",
            "",
            "These values are deliberately not converted into source booleans. The exact immutable candidate must supply the named workflow artifacts.",
            "",
            "| Gate | Required state |",
            "|---|---|",
        ]
    )
    for key, value in qualification.items():
        lines.append(f"| `{key}` | `{value}` |")
    lines.extend(
        [
            "",
            "## External evidence gates",
            "",
            "Repository source and CI cannot self-issue these facts.",
            "",
            "| Gate | Closed? |",
            "|---|---|",
        ]
    )
    for key, value in external.items():
        lines.append(f"| `{key}` | **{'yes' if value else 'no'}** |")
    lines.extend(
        [
            "",
            "## Normative documents",
            "",
        ]
    )
    for path in state["normativeDocuments"]:
        lines.append(f"- `{path}`")
    lines.extend(
        [
            "",
            "## Interpretation",
            "",
            "The current source implements the evaluator, canonical product composition, sealed repository-consumer admission, idempotent publication reconciliation, an audited attempt state machine, and checkpoint/compaction primitives. Production implementation remains false until a named target host binds authentication, durable namespaces, storage semantics, live evidence, and independent acceptance. Eligibility remains `DENY_ALL` and is never selection, activation, promotion, or release.",
            "",
        ]
    )
    return "\n".join(lines)


def verify_source(state: dict) -> None:
    if state.get("schema") != "hepta.learning-eval.current-state.v1":
        fail("unexpected state schema")
    if state.get("module") != "learning.eval" or state.get("authority") != "deny_all":
        fail("module or authority boundary changed")

    lib = LIB_PATH.read_text(encoding="utf-8")
    required = (
        "mod attempt_journal;",
        "mod audited_runner;",
        "mod checkpoint_holdout_file;",
        "mod evidence_sink;",
        "mod repository_admission;",
        "pub(crate) use signed_evaluation::decide_with_signed_evidence_v2;",
        "pub(crate) use longitudinal_time::decide_with_signed_longitudinal_evidence_v3;",
        "pub use audited_runner::AuditedProductEvaluationRunnerV1;",
        "pub use checkpoint_holdout_file::LockedCheckpointFinalHoldoutCasStoreV1;",
        "pub use evidence_sink::ReconcilingQualificationEvidenceSinkV1;",
        "pub use repository_admission::admit_repository_evaluation_v1;",
    )
    for token in required:
        if token not in lib:
            fail(f"missing source boundary token: {token}")
    for token in (
        "pub use signed_evaluation::decide_with_signed_evidence_v2;",
        "pub use longitudinal_time::decide_with_signed_longitudinal_evidence_v3;",
    ):
        if token in lib:
            fail(f"raw primitive is public: {token}")

    registered = {row["path"] for row in state["repositoryConsumers"]}
    mapping = load_json(MAP_PATH)
    mapped = {
        row.get("sourcePath")
        for row in mapping.get("productCallers", [])
        if isinstance(row, dict)
    }
    missing = registered - mapped
    if missing:
        fail(f"implementation map is missing consumers: {sorted(missing)}")

    violations: list[str] = []
    for path in (ROOT / "codex-rs").rglob("*.rs"):
        if path.is_relative_to(EVAL_ROOT):
            continue
        text = path.read_text(encoding="utf-8")
        for symbol in RAW_PRIMITIVES:
            if re.search(rf"\b{re.escape(symbol)}\b", text):
                violations.append(f"{path.relative_to(ROOT)}:{symbol}")
    if violations:
        fail("external raw-decision references: " + ", ".join(sorted(violations)))

    for path in state["normativeDocuments"]:
        if not (ROOT / path).is_file():
            fail(f"missing normative document: {path}")


def verify() -> None:
    state = load_json(STATE_PATH)
    verify_source(state)
    expected = render(state)
    if not STATUS_PATH.is_file():
        fail(f"missing generated status: {STATUS_PATH.relative_to(ROOT)}")
    actual = STATUS_PATH.read_text(encoding="utf-8")
    if actual != expected:
        fail("CURRENT_STATUS.md is stale; run the status generator")
    print(
        json.dumps(
            {
                "schema": "hepta.learning-eval.current-status-verification.v1",
                "module": state["module"],
                "repositoryConsumers": len(state["repositoryConsumers"]),
                "externalGatesClosed": sum(
                    1 for value in state["externalEvidenceGates"].values() if value
                ),
                "status": "verified",
            },
            sort_keys=True,
        )
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=("render", "verify"))
    args = parser.parse_args()
    state = load_json(STATE_PATH)
    if args.command == "render":
        verify_source(state)
        STATUS_PATH.write_text(render(state), encoding="utf-8")
    else:
        verify()


if __name__ == "__main__":
    main()
