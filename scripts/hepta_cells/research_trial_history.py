"""Exercise the development runner with the retained five-task history capsule.

This catalog explicitly includes exposed before/after reference code and golden
oracles. It validates real execution and accounting, never a learned repair or a
new B/C/D result. The caller must provide an existing trusted historical capsule.
"""

import argparse
import json
from pathlib import Path
import shutil
import sys

from .research_trial import sha256
from .research_trial_runner import DevelopmentTrial, write_original

ENTRY = """import subprocess, sys
from pathlib import Path
output = Path(sys.argv[1]) / "historical"
raise SystemExit(subprocess.call([sys.executable, "-I", "-B", "run_all.py", "--output", str(output)]))
"""

ORACLE = """import json, sys
from pathlib import Path
report = json.loads((Path(sys.argv[1]) / "historical" / "VERIFICATION.json").read_text())
tasks = {"original_child_terminal", "terminal_nonce_witness", "native_loader_identity", "qualification_callback_identity", "population_policy_recovery"}
success = (report["status"] == "PASS" and set(report["tasks"]) == tasks
    and report["task_count"] == 5 and report["dependence_groups"] == 3
    and all(v == {"historical_before_semantic_pass": False, "historical_after_semantic_pass": True, "expected_red_green_observed": True} for v in report["tasks"].values())
    and report["cell_repair_learning_demonstrated"] is False
    and report["current_candidate_qualified"] is False)
print(json.dumps({"success": success, "scope": "exposed historical reference replay; not a Cell-generated repair", "historical_tasks": sorted(tasks), "declared_dependency_groups": 3, "fresh_confirmation": 0}))
"""


def run_history(capsule, output):
    source, output = Path(capsule).resolve(strict=True), Path(output).absolute()
    original = json.loads((source / "SHA256SUMS.json").read_text())
    files = {name: identity["sha256"] for name, identity in original["files"].items()}
    files["SHA256SUMS.json"] = sha256((source / "SHA256SUMS.json").read_bytes())
    output.mkdir(parents=True, exist_ok=False)
    staging = output / "staging"
    staging.mkdir()
    for name, expected in files.items():
        relative = Path(name)
        if (
            relative.is_absolute()
            or ".." in relative.parts
            or (source / relative).resolve(strict=True) != source / relative
        ):
            raise ValueError("unsafe historical capsule path")
        raw = (source / relative).read_bytes()
        if sha256(raw) != expected:
            raise ValueError("historical capsule differs: " + name)
        target = staging / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source / relative, target)
    for name, text in (("history_entry.py", ENTRY), ("history_oracle.py", ORACLE)):
        (staging / name).write_text(text)
        files[name] = sha256(text.encode())
    executable = Path(sys.executable).resolve()
    plan = {
        "schema": "hepta.development-trial.v1",
        "mode": "development",
        "runtime": {
            "executable": str(executable),
            "sha256": sha256(executable.read_bytes()),
            "version": sys.version,
        },
        "files": files,
        "tasks": {
            "historical_capsule": {
                "source_groups": [
                    "runtime_terminal",
                    "cell_policy_identity",
                    "native_loader",
                ],
                "phase": "development",
                "exposure": "historical_gold_read",
            }
        },
        "tools": {
            "replay_reference_catalog": [
                "{python}",
                "-I",
                "-B",
                "history_entry.py",
                "{output}",
            ]
        },
        "oracle": ["{python}", "-I", "-B", "history_oracle.py", "{output}"],
        "arms": ["historical_reference"],
        "schedule": [
            {
                "attempt_id": "historical_reference_once",
                "task_id": "historical_capsule",
                "arm": "historical_reference",
                "tool_id": "replay_reference_catalog",
            }
        ],
        "attempt_limit_per_arm": 1,
        "timeout_seconds": 120,
        "catalog_scope": "Exposed before/after historical reference catalog including gold patches/oracles; no candidate generated by a Cell and no new research sources.",
    }
    trial = DevelopmentTrial.create(output / "trial", plan=plan, capsule_root=staging)
    trial.execute("historical_reference_once")
    report = trial.report()
    write_original(output / "REPORT.json", report)
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--capsule", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    report = run_history(args.capsule, args.output)
    print(
        json.dumps(
            {
                "charged": report["trial"]["charged"],
                "outcomes": report["task_observation"]["outcomes"],
                "fresh_confirmation": 0,
                "research_result": None,
            },
            sort_keys=True,
        )
    )
    raise SystemExit(
        0 if report["task_observation"]["outcomes"] == {"success": 1} else 1
    )
